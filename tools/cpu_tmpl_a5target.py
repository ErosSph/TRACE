#!/usr/bin/env python3
"""Target layer for angelo5fix (environment inside the AST: wrapper memory), modelled on tools/cpu_tmpl_sttarget.py (Steel).

Definitions mirror the validated simulator Angelo5Run: seed (reset input high, memory array = packed image), `initialize`, reset asserted,
two rising/falling clock pairs under reset, reset released after a falling edge (A5_BOOT); `actual_cycle` = rise then fall;
`actual_observe`: in the driven state at the rising edge a commit is `writeback_ce` (pc = `memoryaccess_pc`).
Boot facts hold for EVERY image by computation (image enters through the memory array and the registered read `inst`, which is the
only image-dependent boot register).  Roles from the manifest (pipeline_roles.observer, events).  Untrusted; Coq checks.
proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.
"""
import argparse, json, sys
from pathlib import Path
import cpu_tmpl_ast as T

PROFILE = Path('framework/auto-contract-profiles')

TEXT = r"""(** @DESIGN@ target: rising/falling edge, cycle, observer, real reset, boot facts. Generated by tools/cpu_tmpl_a5target.py.
    proof_author: @AUTHOR@; external_llm_api_calls=0.  Environment (phase A): one 128-word memory inside the AST (word i = image[i]),
    reset (active low) asserted, 2 clock cycles under reset, released after a falling edge. *)
From Coq Require Import ZArith List Bool.
Require Import Lang.ExtendedSV Ex.External.CV32E40PTwoCommitITreeInterface @AST@.
Import ListNotations ExtendedSV CV32E40PTwoCommitITreeInterface @ASTNS@.
Local Open Scope Z_scope.
Module @MOD@.
Notation P := @PROG@.
Definition rd (s:State)(r:nat):Z:=read_signal s r.
Definition clock_event (s:State)(v:Z):Event:={|changed_signal:=@CLK@%nat;old_value:=read_signal s @CLK@%nat;new_value:=v|}.
Definition reset_event (s:State)(v:Z):Event:={|changed_signal:=@RST@%nat;old_value:=read_signal s @RST@%nat;new_value:=v|}.
Definition rise (s:State):State:=PhaseSemantics P (clock_event s 1) s.
Definition fall (s:State):State:=PhaseSemantics P (clock_event s 0) s.
Definition actual_cycle (image:list Z)(s:State):State:=fall (rise s).
Definition ram_pack (image:list Z):Z:=fold_right (fun w acc=>Z.lor (norm 32 w) (Z.shiftl acc 32)) 0 image.
Definition seed_x (x:Z):State:=write_signal (write_signal [] @RST@%nat 1) @MEM@%nat x.
Definition boot_x (x:Z):State:=
 let s0 := initialize P (seed_x x) in
 let s1 := PhaseSemantics P (reset_event s0 0) s0 in
 let s5 := fall (rise (fall (rise s1))) in
 PhaseSemantics P (reset_event s5 1) s5.
Definition actual_reset (image:list Z):State:=boot_x (ram_pack image).
Definition driven (s:State):State:=phase_driven_state P (clock_event s 1) s.
Definition actual_observe (s:State):CycleCommits:=
 let d:=driven s in if Z.eqb (norm 1 (rd d @WBCE@%nat)) 1 then OneCommit (norm 32 (rd d @WBPC@%nat)) else SilentCycle.
Definition ce_chain : list nat := [@CES@]%nat.
Lemma actual_reset_x image: actual_reset image = boot_x (ram_pack image).
Proof. reflexivity. Qed.
Theorem boot_regs (image:list Z): map (rd (actual_reset image)) (ce_chain ++ [@WBCE@;@WBPC@;@RST@;@MEM@]%nat) = [@ZEROS@; 1; ram_pack image].
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. vm_compute. reflexivity. Qed.
Theorem boot_rf_zero (image:list Z): rd (actual_reset image) @BANK@%nat = 0.
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. vm_compute. reflexivity. Qed.
Theorem observe_boot (image:list Z): actual_observe (actual_reset image) = SilentCycle.
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. unfold actual_observe, driven. vm_compute. reflexivity. Qed.
(** the first two cycles after boot are silent for every image (the 6-cycle version with a symbolic memory word did not finish in 10 min of vm_compute; the pipeline needs 6 cycles to fill) *)
Theorem silent_prefix (image:list Z): map (fun n => actual_observe (Nat.iter n (actual_cycle image) (actual_reset image))) (seq 0 2) = repeat SilentCycle 2.
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. vm_compute. reflexivity. Qed.
End @MOD@.
Print Assumptions @MOD@.boot_regs.
Print Assumptions @MOD@.boot_rf_zero.
Print Assumptions @MOD@.observe_boot.
Print Assumptions @MOD@.silent_prefix.
"""


def build(design, module):
    prof = json.loads((PROFILE / (design + '.json')).read_text())
    ast = prof['pipeline_roles']['ast']
    pr, tr = prof['pipeline_roles'], prof['template_roles']
    ces = [x['id'] for x in tr['control_chain']['ce']]
    m = dict(DESIGN=design, AUTHOR=T.PROOF_AUTHOR, AST=ast['module'], ASTNS=ast['program'].split('.')[0], MOD=module, PROG=ast['program'].split('.')[-1],
             CLK=str(pr['events']['clock']['id']), RST=str(pr['events']['reset']['id']), MEM=str(tr['environment']['memory']['id']),
             WBCE=str(pr['observer']['commit_valid']['id']), WBPC=str(pr['observer']['commit_pc']['id']), BANK=str(pr['rf_write']['bank']['id']),
             CES=';'.join(str(c) for c in ces), ZEROS='; '.join(['0'] * (len(ces) + 2)))
    t = TEXT
    for k, v in m.items():
        t = t.replace('@' + k + '@', v)
    return t, [f'{module}.{x}' for x in ('boot_regs', 'boot_rf_zero', 'observe_boot', 'silent_prefix')]


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--design', default='angelo5fix'); ap.add_argument('--module', default='A5TmplTarget')
    ap.add_argument('--out', required=True); ap.add_argument('--namespace'); ap.add_argument('--accept', action='store_true')
    a = ap.parse_args()
    text, exports = build(a.design, a.module)
    if a.accept:
        import cpu_tmpl_accept as acc
        prof = json.loads((PROFILE / (a.design + '.json')).read_text())
        lp = [(prof['pipeline_roles']['ast']['file'].rsplit('/', 1)[0], prof['pipeline_roles']['ast']['module'].split('.')[0])]
        r = acc.accept(a.out, a.namespace, a.module, text, exports, lp, extra=dict(generator='tools/cpu_tmpl_a5target.py', design=a.design))
        print(json.dumps({k: v for k, v in r.items() if k != 'loadpaths'}, indent=1)); sys.exit(0 if (r['accepted'] or r.get('coqc_accepted')) else 1)
    Path(a.out).write_text(text); print(a.out)
