# ---- robustness of the root-106 bridge closers (tmpl-econd-casesplit-20261111-a1) ----
# The R106 closers end in a bridge lemma that states the ISA operand order (rs1 operand = root 53, rs2 / immediate operand =
# roots 54 / 59).  Two shapes of a correct datapath do not match it syntactically: (a) the operands of a commutative operator
# written in the other order (`b + a`), (b) a guarded expression `g ? x : y` whose guard reads a root outside the context
# hypotheses (an unconstrained counter) and whose branches are each acceptable (e.g. `g ? x : x`).  For (a) the closer is
# retried after the commutativity lemma, for (b) the proof case-splits on the guard and runs the closer in BOTH branches.
# Nothing is assumed: a closer that fails in one branch fails the module (a FAULT for a deep fault).  Expressions of the
# original NERV design have neither shape, so its module text is unchanged.
A_ROOTS, B_ROOTS = {53}, {54, 59}
COMM = {'BAdd': ('?x + ?y', 'Z.add_comm'), 'BAnd': ('Z.land ?x ?y', 'Z.land_comm'), 'BOr': ('Z.lor ?x ?y', 'Z.lor_comm'),
        'BXor': ('Z.lxor ?x ?y', 'Z.lxor_comm'), 'BMul': ('?x * ?y', 'Z.mul_comm')}


def parse_expr(s):
    """Coq Expr text -> nested tuple (head, args...); atoms are strings"""
    toks = re.findall(r'\(|\)|[^\s()]+', s)
    pos = 0

    def term():
        nonlocal pos
        tk = toks[pos]; pos += 1
        if tk != '(':
            return tk
        items = []
        while toks[pos] != ')':
            items.append(term())
        pos += 1
        return tuple(items)
    return term()


def roots_of(e):
    if isinstance(e, str):
        return set()
    if e and e[0] == 'EVar':
        return {int(e[2].split('%')[0])}
    out = set()
    for x in e[1:]:
        out |= roots_of(x)
    return out


def shape_notes(e):
    """(commuted operator heads, guard roots) of an expression"""
    comm, guard = [], []

    def go(x):
        if isinstance(x, str) or not x:
            return
        if x[0] == 'EBinary' and x[2] in COMM:
            l, r = roots_of(x[3]), roots_of(x[4])
            if l & B_ROOTS and r & A_ROOTS and not (l & A_ROOTS) and x[2] not in comm:
                comm.append(x[2])
        if x[0] == 'ECond':
            for g in sorted(roots_of(x[2]) - A_ROOTS - B_ROOTS):
                if g not in guard:
                    guard.append(g)
        for y in x[1:]:
            go(y)
    go(e)
    return comm, guard


def one_tactic(s):
    """`a. b. c.` (sentences without goal selectors or bullets) -> `a; b; c`"""
    parts = [x.strip() for x in re.split(r'\.(?:\s+|$)', s.strip()) if x.strip()]
    return '; '.join(f'({x})' for x in parts)


def r106_line(c, e106):
    head = ' - rewrite K106. ev_tac. rewrite ?C53, ?C54, ?C45, ?I59. '
    comm, guard = shape_notes(parse_expr(e106))
    if not comm and not guard:
        return head + R106[c]
    T = one_tactic(R106[c])
    alts = [f'({T})'] + [f'(match goal with |- context [{COMM[o][0]}] => rewrite ({COMM[o][1]} x y); {T} end)' for o in comm]
    if guard:   # the ECond adds one `norm w` around the selected branch: also try the closer after removing it
        alts += [f'(rewrite norm_idempotent; {a})' for a in alts]
    tac = 'first [ ' + ' | '.join(alts) + ' ]'
    if guard:
        g = ' | '.join(f'context [read_signal d {r}%nat] => idtac' for r in guard)
        tac = (f'(repeat match goal with |- context [Z.eqb ?g 0] => match g with {g} end; destruct (Z.eqb g 0) end); cbv iota; ' + f'({tac})')
    return head + tac + '.'


