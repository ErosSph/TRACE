def balanced(s, i):
    """the balanced parenthesised term starting at s[i] == '('"""
    assert s[i] == '('
    d = 0
    for j in range(i, len(s)):
        d += {'(': 1, ')': -1}.get(s[j], 0)
        if d == 0:
            return s[i:j + 1]
    raise ValueError


