#!/usr/bin/env python3
"""NERV per-class controller facts (29 classes) through the HAVOC executor (src/Lang/ExtendedSVSymExecHavoc.v).
Untrusted generator, Coq re-checks.  Fast-store pattern in TWO modules (a freshly built overlay constant costs ~1 minute on its first use
by vm_compute, so the big prefix overlay lives in its own compiled module):
  pre   : NervTmplCtlPre  = writer table, the class-independent derived facts F_tail, the overlay `ovP` of statements 0..96 of the controller
          process (everything before the opcode `case`), executed ONCE.
  cls   : NervTmplCtl     = per class C: the tail (statements 97..99) is executed under the class facts and compared with the printed
          expression X in ONE closed boolean check (`hx2_out2`); statement
              norm w (read d R) = norm w (eval_expr d X)      (X = executor expression for R simplified under the facts)
Commands: f_tail | gen-pre | accept-pre | probe | gen-cls | accept-cls.
proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0."""
import argparse, json, re, sys, time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import cpu_tmpl_nvlib as L
import cpu_isa_classes as isa
ROOT = L.ROOT
CACHE = ROOT / 'scratch-nv'
CTL = 334            # position of the controller (process_354) in the comb list
K = 97               # first statement of the opcode case
OUTS = [(44, 32), (105, 1), (106, 32), (107, 5), (112, 1), (33, 1), (29, 1), (114, 1), (113, 1), (108, 1), (111, 1)]
BASE = [(1, 1, 0), (109, 1, 0), (38, 1, 0)]
PRE_DIR = ROOT / 'results/r-tmpl-nerv-ctlpre-20261104-a2'
PRE_NS = 'TmplNervCtlPre'


def facts_of(c):
    f = list(BASE) + [(52, 7, c['opcode'])]
    f3 = c['funct3'] if c['funct3'] is not None else (0 if c['name'] == 'Jalr' else None)
    if f3 is not None:
        f.append((50, 3, f3))
    if c['funct7'] is not None:
        f.append((47, 7, c['funct7']))
    elif c['opcode'] == 19 and f3 is not None:      # OP-IMM without funct7 constraint: the guard `{funct7,funct3} & 7 == k` needs the low bits
        f.append(('raw', f'EBinary 10 BAnd (EConcat 10 (EVar 7 47%nat) (EVar 3 50%nat)) (EConst 10 7), {f3}'))
    return f


BUBBLES = [dict(name='Bub01', facts=[(1, 1, 0), (109, 1, 1), (38, 1, 0)], opcode=None),
           dict(name='Bub10', facts=[(1, 1, 1), (109, 1, 0), (38, 1, 0)], opcode=None)]


def all_cases():
    cl = [dict(c, facts=facts_of(c)) for c in isa.classes()]
    return cl + [dict(b, funct3=None, funct7=None) for b in BUBBLES]


def facts_text(fs):
    return '[' + '; '.join((f'({x[1]})' if x[0] == 'raw' else f'(EVar {x[1]} {x[0]}%nat, {x[2]})') for x in fs) + ']'


HDR = '''From Coq Require Import ZArith List Bool.
Require Import Lang.ExtendedSV Lang.ExtendedSVSymExec Lang.ExtendedSVFactChain Lang.ExtendedSVSymExecSym Lang.ExtendedSVEval4
 Lang.ExtendedSVSymExecOverlay4 Lang.ExtendedSVSymExecHavoc Lang.ExtendedSVSymExecHavocMulti NervLit.NervLitAST@REQ@.
Import ListNotations ExtendedSV ExtendedSVSymExec ExtendedSVFactChain ExtendedSVSymExecSym ExtendedSVEval4 ExtendedSVSymExecOverlay4 ExtendedSVSymExecHavoc ExtendedSVSymExecHavocMulti.
Local Open Scope Z_scope.
'''
COMMON = '''Notation P := NervLitAST.nerv_program.
Definition ps := filter is_comb (processes P).
Definition defproc : Process := {| process_kind:=Initial; process_events:=[]; process_body:=SSkip; process_source_line:=0%nat |}.
Definition proc334 := nth 334 ps defproc.
Definition stl := match process_body proc334 with SSeq [SSeq l] => l | _ => [] end.
Definition ks : list nat := seq 0 334.
'''
PDEC = 'Definition pdec : forall a b : Expr * Z, {a=b}+{a<>b}. Proof. decide equality; [apply Z.eq_dec | apply expr_eq_dec]. Defined.\n'


def run_coq(txt, extra=(), query=None, cache=None):
    cache=Path(cache) if cache is not None else CACHE
    cache.mkdir(exist_ok=True)
    return (query or L.coqc)(txt, workdir=str(cache), extra=extra)


def f_tail(query=None, cache=None):
    cache=Path(cache) if cache is not None else CACHE
    cl = isa.classes()
    t = HDR.replace('@REQ@', '') + 'Set Printing Width 1000000.\n' + COMMON + L.wtab_text()
    t += 'Eval vm_compute in (skipn ' + str(len(facts_of(cl[0]))) + ' (hx_pass ps wtab (statement_fuel P) ' + facts_text(facts_of(cl[0])) + ' ks)).\n'
    out = run_coq(t, query=query, cache=cache)
    m = re.split(r'(?m)^     = ', out)[1]
    ft = re.sub(r'\s+', ' ', m.split('\n     : ')[0]).strip()
    (cache / 'f_tail.txt').write_text(ft)
    print('f_tail', len(ft))


def pre_text(cache=None):
    cache=Path(cache) if cache is not None else CACHE
    ft = (cache / 'f_tail.txt').read_text()
    L_ = ['(** NERV controller facts, shared part: writer table, class-independent derived facts and the prefix overlay (statements 0..%d of the' % (K - 1),
          '    controller process). Generated by tools/cpu_tmpl_nvctl.py gen-pre.  proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0. Generated. *)',
          HDR.replace('@REQ@', '').rstrip(), 'Module NervTmplCtlPre.', COMMON.rstrip(), L.wtab_text().strip(), PDEC.rstrip(),
          'Lemma wtab_ok : tab_okb ps wtab = true. Proof. vm_compute; reflexivity. Qed.',
          'Definition ps_eq : filter is_comb (processes P) = ps := eq_refl.',
          f'Lemma nth_ok : nth_error ps {CTL} = Some proc334. Proof. vm_compute; reflexivity. Qed.',
          f'Lemma body_eq : nbfix (process_body proc334) = SSeq [SSeq (firstn {K} stl ++ skipn {K} stl)]. Proof. vm_compute; reflexivity. Qed.',
          'Lemma fuel_eq : statement_fuel P = S (S 510%nat). Proof. vm_compute; reflexivity. Qed.',
          'Lemma body_eq0 : nbfix (process_body proc334) = SSeq [SSeq ([] ++ stl)]. Proof. vm_compute; reflexivity. Qed.',
          'Lemma emp_ok : hxl [] 510 [] [] = Some []. Proof. reflexivity. Qed.',
          f'Lemma emp_inp : facts_inputs_okb [] wtab {CTL} = true. Proof. vm_compute; reflexivity. Qed.',
          f'Definition F_base : Facts := {facts_text(BASE)}.',
          f'Definition F_tail : Facts := {ft}.',
          'Definition F_pre : Facts := F_base ++ F_tail.',
          f'Definition ovP : SOv := Eval vm_compute in match hxl F_pre 510 (firstn {K} stl) [] with Some o => o | None => [] end.',
          f'Lemma ovP_ok : hxl F_pre 510 (firstn {K} stl) [] = Some ovP. Proof. vm_compute; reflexivity. Qed.',
          f'Lemma pre_inp : facts_inputs_okb F_pre wtab {CTL} = true. Proof. vm_compute; reflexivity. Qed.',
          'End NervTmplCtlPre.', 'Goal True. idtac "TMPL_AUDIT_BEGIN". exact I. Qed.',
          'Print Assumptions NervTmplCtlPre.ovP_ok.', 'Print Assumptions NervTmplCtlPre.body_eq.']
    return '\n'.join(L_) + '\n', ['NervTmplCtlPre.ovP_ok', 'NervTmplCtlPre.body_eq']


def split_top(txt):
    """split a printed Coq list '[a; b; c]' at depth-0 '; '"""
    txt = txt.strip()
    assert txt.startswith('[') and txt.endswith(']'), txt[:80]
    body, depth, cur, out = txt[1:-1], 0, '', []
    i = 0
    while i < len(body):
        ch = body[i]
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if depth == 0 and body[i:i + 2] == '; ':
            out.append(cur); cur = ''; i += 2; continue
        cur += ch; i += 1
    if cur.strip():
        out.append(cur)
    return out


def probe(query=None, cache=None, pre_dir=None):
    cache=Path(cache) if cache is not None else CACHE
    pre_dir=Path(pre_dir) if pre_dir is not None else PRE_DIR
    cases = all_cases()
    t = HDR.replace('@REQ@', f' {PRE_NS}.NervTmplCtlPre') + 'Set Printing Width 1000000.\nModule PRE := ' + f'{PRE_NS}.NervTmplCtlPre.NervTmplCtlPre.\nImport PRE.\n'
    roots = '[' + ';'.join(f'{r}%nat' for r, w in OUTS) + ']'
    for i, c in enumerate(cases):
        n = c['name']
        fs = c['facts']
        pref = c['opcode'] is not None
        t += f'Definition F0_{i} : Facts := ' + (f'F_base ++ {facts_text(fs[len(BASE):])}' if pref else facts_text(fs)) + '.\n'
        t += f'Definition F1_{i} : Facts := Eval vm_compute in (hx_pass ps wtab (statement_fuel P) F0_{i} ks).\n'
        if pref:
            t += f'Eval vm_compute in (if list_eq_dec pdec (skipn (length F0_{i}) F1_{i}) F_tail then 1 else 0).\n'
            run = f'hxl F1_{i} 510 (skipn {K} stl) ovP'
        else:
            t += 'Eval vm_compute in 1.\n'
            run = f'hxl F1_{i} 510 stl []'
        t += f'Eval vm_compute in (match {run} with Some o => map (fun r => (r, option_map (fun p => (fst p, simp4 F1_{i} (snd p))) (sov_lookup o r))) {roots} | None => [] end).\n'
    t0 = time.time()
    out = run_coq(t, extra=['-R', str(pre_dir), PRE_NS], query=query, cache=cache)
    secs = time.time() - t0
    chunks = [re.sub(r'\s+', ' ', x.split('\n     : ')[0]).strip() for x in re.split(r'(?m)^     = ', out)[1:]]
    res, p = {}, 0
    for c in cases:
        same = chunks[p]; p += 1
        items = split_top(chunks[p]); p += 1
        outs = {}
        for it in items:
            m = re.match(r'\((\d+)%nat, (.*)\)$', it.strip())
            outs[int(m.group(1))] = m.group(2)
        res[c['name']] = dict(tail_same=same.strip() == '1', outs=outs)
    (cache / 'ctl_probe.json').write_text(json.dumps(dict(classes=res, seconds=secs), indent=1))
    print('probe', secs, 's', {k: v['tail_same'] for k, v in res.items()})


def parse_out(s):
    if s == 'None':
        return None
    m = re.match(r'Some \((\d+)%nat, (.*)\)$', s)
    assert m, s
    return int(m.group(1)), m.group(2)


def cls_text(names=None, cache=None):
    cache=Path(cache) if cache is not None else CACHE
    d = json.loads((cache / 'ctl_probe.json').read_text())
    cases = [c for c in all_cases() if names is None or c['name'] in names]
    L_ = ['(** NERV per-class controller facts via the havoc executor. Generated by tools/cpu_tmpl_nvctl.py gen-cls.',
          '    proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0. Generated. *)',
          HDR.replace('@REQ@', f' {PRE_NS}.NervTmplCtlPre').rstrip(), 'Module NervTmplCtl.', f'Module PRE := {PRE_NS}.NervTmplCtlPre.NervTmplCtlPre.', 'Import PRE.',
          'Lemma nofacts s : FactsHold s []. Proof. intros e z H. destruct H. Qed.']
    exports, claimed = [], {}
    for c in cases:
        n = c['name']
        fs = c['facts']
        pref = c['opcode'] is not None
        info = d['classes'][n]
        assert info['tail_same'], n
        L_ += [f'Definition F0_{n} : Facts := ' + (f'F_base ++ {facts_text(fs[len(BASE):])}' if pref else facts_text(fs)) + '.',
               f'Definition F1_{n} : Facts := Eval vm_compute in (hx_pass ps wtab (statement_fuel P) F0_{n} ks).',
               f'Lemma F1_{n}_eq : hx_pass ps wtab (statement_fuel P) F0_{n} ks = F1_{n}. Proof. vm_compute; reflexivity. Qed.',
               f'Lemma inp_{n} : facts_inputs_okb F1_{n} wtab {CTL} = true. Proof. vm_compute; reflexivity. Qed.']
        if pref:
            L_ += [f'Lemma tail_{n} : skipn (length F0_{n}) F1_{n} = F_tail. Proof. vm_compute; reflexivity. Qed.']
        trip, concl = [], []
        for r, w in OUTS:
            po = parse_out(info['outs'].get(str(r), info['outs'].get(r, 'None')))
            if po is None or po[0] == 0:
                continue
            ww, X = po
            trip.append((r, ww, X))
            concl.append(f'norm {ww} (read_signal d {r}%nat) = norm {ww} (eval_expr d ({X}))')
        claimed[n] = [t_[0] for t_ in trip]
        lst = '[' + '; '.join(f'({r}%nat, {ww}%nat, ({X}))' for r, ww, X in trip) + ']'
        stmt = ' /\\\n  '.join(f'({c_})' for c_ in concl)
        sel = '(ltac:(cbn [In]; repeat first [left; reflexivity | right]))'
        comps = [f'(HM ({r}%nat, {ww}%nat, ({X})) {sel})' for r, ww, X in trip]
        pf = comps[-1]
        for p_ in reversed(comps[:-1]):
            pf = f'(conj {p_} {pf})'
        if pref:
            call = (f'hx2_out_m P ps wtab {CTL} proc334 (firstn {K} stl) (skipn {K} stl) F_pre F1_{n} ovP 510 seed d {lst} ps_eq (tab_okb_sound _ _ wtab_ok) nth_ok inp_{n} pre_inp HF1 HFt HL body_eq fuel_eq ovP_ok (ltac:(vm_compute; reflexivity))')
            hft = (f' assert (Hd : FactsHold d F_tail) by (rewrite <- tail_{n}; exact (factshold_skipn _ _ _ HF1)).'
                   f' assert (HFt : FactsHold d F_pre) by (exact (factshold_app d F_base F_tail (factshold_app_l _ _ _ HF0) Hd)).')
        else:
            call = (f'hx2_out_m P ps wtab {CTL} proc334 [] stl [] F1_{n} [] 510 seed d {lst} ps_eq (tab_okb_sound _ _ wtab_ok) nth_ok inp_{n} emp_inp HF1 (nofacts d) HL body_eq0 fuel_eq emp_ok (ltac:(vm_compute; reflexivity))')
            hft = ''
        L_ += [f'Theorem {n}_ctl seed d : CombLFP P seed d -> FactsHold d F0_{n} ->\n  {stmt}.',
               'Proof. intros HL HF0.',
               f' assert (HF1 : FactsHold d F1_{n}) by (rewrite <- F1_{n}_eq; exact (hx_pass_sound P ps wtab (statement_fuel P) seed d ps_eq (tab_okb_sound _ _ wtab_ok) eq_refl HL ks F0_{n} HF0)).',
               hft, f' pose proof ({call}) as HM.', f' exact {pf}. Qed.']
        exports.append(f'{n}_ctl')
    L_ += ['End NervTmplCtl.', 'Goal True. idtac "TMPL_AUDIT_BEGIN". exact I. Qed.'] + [f'Print Assumptions NervTmplCtl.{x}.' for x in exports]
    return '\n'.join(L_) + '\n', ['NervTmplCtl.' + x for x in exports], d, claimed


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['f_tail', 'gen-pre', 'accept-pre', 'probe', 'gen-cls', 'accept-cls'])
    ap.add_argument('--out')
    ap.add_argument('--classes')
    ap.add_argument('--module', default='NervTmplCtl')
    ap.add_argument('--timeout', type=int, default=3600)
    a = ap.parse_args()
    lp = [('experiments/framework/generated/nerv-lit', 'NervLit')]
    import cpu_tmpl_accept as acc
    if a.cmd == 'f_tail':
        f_tail(); sys.exit(0)
    if a.cmd == 'probe':
        probe(); sys.exit(0)
    if a.cmd in ('gen-pre', 'accept-pre'):
        text, exports = pre_text()
        if a.cmd == 'gen-pre':
            Path(a.out).write_text(text); sys.exit(0)
        r = acc.accept(a.out, PRE_NS, 'NervTmplCtlPre', text, exports, lp, providers=[], timeout=a.timeout, extra=dict(generator='tools/cpu_tmpl_nvctl.py (pre)', design='nerv'))
        print(json.dumps({k: v for k, v in r.items() if k != 'info'}, indent=1)); sys.exit(0 if r.get('coqc_accepted') else 1)
    names = a.classes.split(',') if a.classes else None
    text, exports, d, claimed = cls_text(names)
    if a.cmd == 'gen-cls':
        Path(a.out).write_text(text); print(a.out, len(text.splitlines()), 'lines'); sys.exit(0)
    prov = [dict(namespace=PRE_NS, directory=str(PRE_DIR))]
    r = acc.accept(a.out, 'TmplNervCtl', 'NervTmplCtl', text, exports, lp, providers=prov, timeout=a.timeout,
                   extra=dict(generator='tools/cpu_tmpl_nvctl.py (cls)', design='nerv', classes=len(exports), probe_seconds=d['seconds'], claimed=claimed))
    print(json.dumps({k: v for k, v in r.items() if k != 'info'}, indent=1)); sys.exit(0 if r.get('coqc_accepted') else 1)
