#!/usr/bin/env python3
"""Target layer for a design whose environment lives inside the AST (Steel): cycle, observer, real reset, rank, boot facts.

Reads the role manifest (framework/auto-contract-profiles/<design>.json, `template_roles`: events, memory, register_file,
pc, fsm, commit, reset_flops, environment).  Output module: the Coq definitions of the target (rising edge; falling edge;
`actual_cycle`; `actual_observe`; `actual_reset` = initialize + `reset_edges` clock cycles under reset + reset release;
memory image packing) and the boot theorems proved by computation for EVERY image (the image enters only through the
memory array, which is the single symbolic value): boot_shape, boot_regs, observe_boot, rank_boot, InvEnv at boot.
Statement/definitions mirror the validated simulator SteelRun (tools/cpu_ast_sim.py).
proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.
"""
import argparse
import json
import sys
from pathlib import Path
import cpu_tmpl_ast as T

PROFILE = Path('framework/auto-contract-profiles')

TEXT = r"""(** @DESIGN@ target: rising/falling edge, cycle, observer, real reset, rank, boot facts.
    Generated by tools/cpu_tmpl_sttarget.py from the role manifest.  proof_author: @AUTHOR@; external_llm_api_calls=0.
    Environment (not design): the wrapper memory is part of the AST; the program image is the initial value of the array
    (@MEMWORDS@ words, word i = image[i], 32-bit); reset is held for @EDGES@ rising edges and released after a falling edge. *)
From Coq Require Import ZArith List Bool.
Require Import Lang.ExtendedSV Ex.External.CV32E40PTwoCommitITreeInterface @AST@.
Import ListNotations ExtendedSV CV32E40PTwoCommitITreeInterface.
Local Open Scope Z_scope.
Module @MOD@.
Notation P := @PROG@.
Definition rd (s:State)(r:nat):Z:=read_signal s r.
Definition clock_event (s:State)(v:Z):Event:={|changed_signal:=@CLK@%nat;old_value:=read_signal s @CLK@%nat;new_value:=v|}.
Definition reset_event (s:State)(v:Z):Event:={|changed_signal:=@RST@%nat;old_value:=read_signal s @RST@%nat;new_value:=v|}.
Definition rise (s:State):State:=PhaseSemantics P (clock_event s 1) s.
Definition fall (s:State):State:=PhaseSemantics P (clock_event s 0) s.
Definition actual_cycle (image:list Z)(s:State):State:=fall (rise s).
Definition ram_pack (image:list Z):Z:=fold_right (fun w acc=>Z.lor (norm 32 w) (Z.shiftl acc 32)) 0 image.
Definition seed_x (x:Z):State:=write_signal (write_signal [] @RST@%nat 1) @RAM@%nat x.
Definition boot_cycles (s:State):State:=@CYCLES@.
Definition boot_x (x:Z):State:=PhaseSemantics P (reset_event (boot_cycles (initialize P (seed_x x))) 0) (boot_cycles (initialize P (seed_x x))).
Definition actual_reset (image:list Z):State:=boot_x (ram_pack image).
(** commit observation: the driven state at the rising edge shows a retiring instruction *)
Definition driven (s:State):State:=phase_driven_state P (clock_event s 1) s.
Definition committing (d:State):bool:=
 Z.eqb (norm 1 (rd d @FLUSH@%nat)) 0 && Z.eqb (norm 1 (rd d @CE@%nat)) 1 && Z.eqb (norm 1 (rd d @LP@%nat)) 0 &&
 Z.eqb (norm 1 (rd d @SP@%nat)) 0 && Z.eqb (norm 1 (rd d @TRAP@%nat)) 0.
Definition actual_observe (s:State):CycleCommits:=let d:=driven s in if committing d then OneCommit (norm 32 (rd d @PC@%nat)) else SilentCycle.
(** the part of the joint invariant that does not mention the ISA state (environment, reset flops, interrupt pending bits) *)
Definition InvEnv (image:list Z)(s:State):Prop:=
 norm 1 (rd s @RRESP@%nat)=norm 1 (rd s @PRR@%nat) /\ norm 1 (rd s @WRESP@%nat)=0 /\ norm 1 (rd s @PWR@%nat)=0 /\ norm 1 (rd s @PLR@%nat)=0 /\
 norm 1 (rd s @ENVRR@%nat)=norm 1 (rd s @RR@%nat) /\ norm 1 (rd s @RST@%nat)=0 /\ rd s @RAM@%nat=ram_pack image /\
 @MIPS@.
Definition st_rank (s:State):nat:=Z.to_nat (norm 1 (rd s @RR@%nat) + (if Z.eqb (norm 4 (rd s @STATE@%nat)) @OPER@ then 0 else 1)).

Lemma actual_reset_x image: actual_reset image = boot_x (ram_pack image).
Proof. reflexivity. Qed.
(** the boot state is the image-independent state with the memory array replaced *)
Theorem boot_shape_x (x:Z): boot_x x = write_signal (boot_x 0) @RAM@%nat x.
Proof. vm_compute. reflexivity. Qed.
Theorem boot_regs (image:list Z): map (rd (actual_reset image)) [@STATE@R;@PC@;@RR@;@ENVRR@;@RD@;@RRESP@;@PRR@;@PLR@;@PWR@;@RST@;@RAM@]%nat
 = [@RESETSTATE@;0;1;1;0;0;0;0;0;0;ram_pack image].
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. vm_compute. reflexivity. Qed.
Theorem boot_inv_env (image:list Z): InvEnv image (actual_reset image).
Proof. rewrite actual_reset_x. unfold InvEnv. generalize (ram_pack image) as x. intro x. rewrite boot_shape_x.
 vm_compute. repeat split; reflexivity. Qed.
Theorem boot_rf_zero (image:list Z): rd (actual_reset image) @BANK@%nat = 0.
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. rewrite boot_shape_x. vm_compute. reflexivity. Qed.
Theorem observe_boot (image:list Z): actual_observe (actual_reset image) = SilentCycle.
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. unfold actual_observe, driven, committing. rewrite boot_shape_x.
 vm_compute. reflexivity. Qed.
Theorem rank_boot (image:list Z): st_rank (actual_reset image) = 2%nat.
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. unfold st_rank. rewrite boot_shape_x. vm_compute. reflexivity. Qed.
(** the two silent cycles after boot, for every image (the reset flops drain, then the FSM leaves RESET) *)
Theorem silent_after_boot (image:list Z): actual_observe (actual_cycle image (actual_reset image)) = SilentCycle
 /\ st_rank (actual_cycle image (actual_reset image)) = 1%nat.
Proof. rewrite actual_reset_x. generalize (ram_pack image) as x. intro x. unfold actual_cycle, actual_observe, driven, committing, st_rank. rewrite boot_shape_x.
 split; vm_compute; reflexivity. Qed.
End @MOD@.
Print Assumptions @MOD@.boot_regs.
Print Assumptions @MOD@.boot_inv_env.
Print Assumptions @MOD@.boot_rf_zero.
Print Assumptions @MOD@.observe_boot.
Print Assumptions @MOD@.rank_boot.
Print Assumptions @MOD@.silent_after_boot.
"""


def build(design, module, pad_seed=False):
    prof = json.loads((PROFILE / (design + '.json')).read_text())
    ast = prof['pipeline_roles']['ast']
    R = prof['template_roles']
    i = lambda d: str(d['id'])
    mips = [186, 187, 188, 189]      # interrupt-pending registers of the manifest's CSR group (set by the discovery below)
    a = T.Ast(ast['file'], ast['signal_table'])
    mips = [k for k in a.sig if a.sig[k]['path'].split('.')[-1] in ('csr_mip_mfip', 'csr_mip_meip', 'csr_mip_mtip', 'csr_mip_msip')]
    edges = R['environment']['reset_edges']
    cyc = 'cyc_' + str(edges)
    body = 's'
    for _ in range(edges):
        body = f'actual_cycle [] ({body})'
    # records of actual_cycle need the image-free form; actual_cycle ignores its image argument
    m = dict(DESIGN=design, AUTHOR=T.PROOF_AUTHOR, AST=ast['module'], MOD=module, PROG=ast['program'], CLK=i(R['events']['clock']),
             RST=i(R['events']['reset']), RAM=i(R['memory']['array']), EDGES=str(edges), MEMWORDS=str(R['memory']['words']),
             CYCLES=body, FLUSH=i(R['commit']['flush']), CE=i(R['commit']['clock_enable']), LP=i(R['commit']['load_pending']),
             SP=i(R['commit']['store_pending']), TRAP=i(R['commit']['take_trap']), PC=i(R['pc']['register']),
             RRESP=str([k for k in a.sig if a.sig[k]['path'].endswith('steel_top.read_response')][0]),
             WRESP=str([k for k in a.sig if a.sig[k]['path'].endswith('steel_top.write_response')][0]),
             PRR=str([k for k in a.sig if a.sig[k]['path'].endswith('core.prev_read_request')][0]),
             PWR=str([k for k in a.sig if a.sig[k]['path'].endswith('core.prev_write_request')][0]),
             PLR=str([k for k in a.sig if a.sig[k]['path'].endswith('core.prev_load_request')][0]),
             RR=str(R['reset_flops']['flops'][1]['id']), ENVRR=str(R['reset_flops']['flops'][0]['id']),
             RD=i(R['memory']['read_data']), STATE=i(R['fsm']['state']), OPER=str(R['fsm']['operating_value']),
             RESETSTATE=str(R['fsm']['reset_value']), BANK=i(R['register_file']['bank']),
             MIPS=' /\\ '.join(f'rd s {k}%nat=0' for k in mips))
    t = TEXT
    if pad_seed:   # additive fix: the initial state has one cell per declared signal (a1 had 332 of 334 cells)
        t = t.replace('Definition seed_x (x:Z):State:=write_signal (write_signal [] @RST@%nat 1) @RAM@%nat x.', 'Definition seed_x (x:Z):State:=write_signal (write_signal (write_signal [] @RST@%nat 1) @RAM@%nat x) ' + str(len(a.sig) - 1) + '%nat 0.')
    # the boot_regs statement uses a literal "R" suffix on the state id only to keep the template readable
    t = t.replace('@STATE@R', '@STATE@')
    for k, v in m.items():
        t = t.replace('@' + k + '@', v)
    exports = [f'{module}.{x}' for x in ('boot_regs', 'boot_inv_env', 'boot_rf_zero', 'observe_boot', 'rank_boot', 'silent_after_boot')]
    return t, exports


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--design', default='steel')
    ap.add_argument('--module', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--namespace')
    ap.add_argument('--accept', action='store_true')
    ap.add_argument('--pad-seed', action='store_true', help='seed_x has one cell per declared signal (fixes target a1 reset length 332 vs 334)')
    a = ap.parse_args()
    text, exports = build(a.design, a.module, a.pad_seed)
    if a.accept:
        import cpu_tmpl_accept as acc
        r = acc.accept(a.out, a.namespace, a.module, text, exports, [('experiments/framework/generated/steel', 'Steel')],
                       extra=dict(generator='tools/cpu_tmpl_sttarget.py', design=a.design))
        print(json.dumps({k: v for k, v in r.items() if k != 'loadpaths'}, indent=1))
        sys.exit(0 if (r['accepted'] or r.get('coqc_accepted')) else 1)
    Path(a.out).write_text(text)
    print(a.out)
