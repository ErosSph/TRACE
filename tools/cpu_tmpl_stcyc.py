def nsig():
    """declared signal count of the configured Steel AST (was the constant 334; an added trigger register adds one;
    tmpl-econd-casesplit-20261111-a1)"""
    import cpu_tmpl_ast as T
    g = Path(__file__).resolve().parent.parent / 'experiments/framework/generated/steel'
    return len(T.Ast(str(g / 'SteelAST.v'), str(g / 'report.json')).sig)


def build(stage_dir, frame_dir):
    st = Path(stage_dir, 'SteelTmplStage.v').read_text()
    fr = Path(frame_dir, 'SteelTmplFrame.v').read_text()
    frames = set(re.findall(r'Theorem fall_frame_(\d+) ', fr))
    regs = []
    for m in re.finditer(r'Theorem rise_(\d+) .*?texpr (\d+)%nat (\d+)%nat \(tree_of(_f)? process_(\d+)\)', st, re.S):
        R, w, R2, flat, k = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
        assert R == R2
        regs.append((int(R), int(w), flat or '', int(k)))
    out = []
    for R, w, flat, k in regs:
        assert str(R) in frames, R
        out.append(f"""Theorem cyc_{R} s : Pre s -> norm {w} (read_signal (TG.fall (TG.rise s)) {R}%nat) = norm {w} (eval_expr (drv s) (texpr {w}%nat {R}%nat (tree_of{flat} process_{k}))).
Proof. intro HP. pose proof HP as HP0. destruct HP0 as (Hl & H0 & H1 & HW & seed & HL). destruct (pre_rise s HP) as (Hl2 & H02 & H12 & HW2 & seed2 & HL2).
 unfold TG.fall. rewrite (FRM.fall_frame_{R} (TG.clock_event (TG.rise s) 0) (TG.rise s) seed2 eq_refl eq_refl H02 H12 HW2 HL2 (LF.driven_lfp _ _ Hl2 (ev_lt _ _))).
 exact (rise_{R} (TG.clock_event s 1) s seed eq_refl eq_refl H0 H1 HW HL (LF.driven_lfp s _ Hl (ev_lt _ _))). Qed.""")
    names = [f'cyc_{R}' for R, *_ in regs]
    text = CORE.replace('@NSIG@', str(nsig())).replace('@REGS@', '\n'.join(out)) + ''.join(f'Print Assumptions SteelTmplCyc.{n}.\n' for n in names)
    return text, [f'SteelTmplCyc.{n}' for n in names], dict(registers=len(regs))


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('--stage', default='results/r-tmpl-steel-stage-20261104-a3')
    ap.add_argument('--frame', default='results/r-tmpl-steel-frame-20261104-a1')
    ap.add_argument('--out', required=True)
    ap.add_argument('--accept', action='store_true')
    ap.add_argument('--module', default='SteelTmplCyc')
    ap.add_argument('--namespace', default='TmplSteelCyc')
    a = ap.parse_args()
    text, exports, info = build(a.stage, a.frame)
    text = text.replace('SteelTmplCyc', a.module)
    exports = [e.replace('SteelTmplCyc', a.module) for e in exports]
    if not a.accept:
        Path(a.out).write_text(text); print(a.out, info); sys.exit(0)
    import cpu_tmpl_accept as acc
    prov = [dict(namespace=n, directory=str(Path(d).resolve())) for n, d in (
        ('TmplSteelEdge', 'results/r-tmpl-steel-edge-20261104-a3'), ('TmplSteelStage', a.stage), ('TmplSteelFrame', a.frame),
        ('TmplSteelTarget', 'results/r-tmpl-steel-target-20261104-a1'), ('TmplSteelLfp', 'results/r-tmpl-steel-lfp-20261104-a1'))]
    r = acc.accept(a.out, a.namespace, a.module, text, exports, [('experiments/framework/generated/steel', 'Steel')], providers=prov,
                   extra=dict(generator='tools/cpu_tmpl_stcyc.py', design='steel', info=info))
    print(json.dumps({k: v for k, v in r.items() if k != 'loadpaths'}, indent=1))
