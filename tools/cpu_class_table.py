#!/usr/bin/env python3
"""Design-independent: Coq lemmas tying the ISA class table (cpu_isa_classes.py) to riscv-coq `Decode.decode`.

Emits src/Ex/External/CPUClassTableCheck.v: for every class C a lemma `decode_C` saying that every word whose
decode-relevant bit slices (opcode, funct3, funct7 / funct6+shamtHi for shift immediates) equal the table entry
decodes to the instruction C with the field-extraction arguments of riscv-coq. The table numbers are therefore
checked against the ISA decoder, not against any RTL.
"""
import sys
from pathlib import Path
import cpu_isa_classes as isa

SX = 'signExtend'
BS = lambda a, b: f'(bitSlice w {a} {b})'
RD, RS1, RS2 = BS(7, 12), BS(15, 20), BS(20, 25)
IMM12 = f'({SX} 12 {BS(20, 32)})'
JIMM = (f'({SX} 21 (Z.lor (Z.lor (Z.lor (Z.shiftl {BS(31, 32)} 20) (Z.shiftl {BS(21, 31)} 1)) '
        f'(Z.shiftl {BS(20, 21)} 11)) (Z.shiftl {BS(12, 20)} 12)))')
SBIMM = (f'({SX} 13 (Z.lor (Z.lor (Z.lor (Z.shiftl {BS(31, 32)} 12) (Z.shiftl {BS(25, 31)} 5)) '
         f'(Z.shiftl {BS(8, 12)} 1)) (Z.shiftl {BS(7, 8)} 11)))')
UIMM = f'({SX} 32 (Z.shiftl {BS(12, 32)} 12))'
SHAMT = f'(machineIntToShamt {BS(20, 26)})'
SHIFT_IMM = {'Slli', 'Srli', 'Srai'}


def isa_f3(c):
    return 0 if c['name'] == 'Jalr' else c['funct3']


def hyps(c):
    h = [f'bitSlice w 0 7 = {c["opcode"]}']
    if isa_f3(c) is not None:
        h.append(f'bitSlice w 12 15 = {isa_f3(c)}')
    if c['name'] in SHIFT_IMM:
        h += [f'bitSlice w 26 32 = {c["funct7"] // 2}', 'bitSlice w 25 26 = 0']
    elif c['group'] == 'OP':
        h.append(f'bitSlice w 25 32 = {c["funct7"]}')
    return h


def args(c):
    n, g = c['name'], c['group']
    if g == 'OP':
        return f'{RD} {RS1} {RS2}'
    if n in SHIFT_IMM:
        return f'{RD} {RS1} {SHAMT}'
    if g == 'OPIMM':
        return f'{RD} {RS1} {IMM12}'
    if g in ('LUI', 'AUIPC'):
        return f'{RD} {UIMM}'
    if g == 'JAL':
        return f'{RD} {JIMM}'
    if g == 'JALR':
        return f'{RD} {RS1} {IMM12}'
    return f'{RS1} {RS2} {SBIMM}'


def text():
    out = ['(** Generated by tools/cpu_class_table.py. proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.',
           '    Design independent: the class table (opcode/funct3/funct7) checked against riscv-coq [Decode.decode]. *)',
           'From Coq Require Import ZArith.', 'Require Import riscv.Spec.Decode riscv.Utility.Utility.',
           'Local Open Scope Z_scope.', 'Module CPUClassTableCheck.']
    names = []
    for c in isa.classes():
        n = c['name']
        names.append(n)
        h = ' -> '.join(hyps(c))
        out.append(f'Lemma decode_{n} w : {h} ->\n Decode.decode Decode.RV32I w = Decode.IInstruction (Decode.{n} {args(c)}).')
        k = len(hyps(c))
        out.append(f'Proof. intros {" ".join("H" + str(i) for i in range(k))}. unfold Decode.decode. cbv zeta. rewrite {", ".join("H" + str(i) for i in range(k))}.')
        out.append(' cbn [Z.eqb Pos.eqb andb orb bitwidth]. reflexivity. Qed.')
    out.append('End CPUClassTableCheck.')
    out += [f'Print Assumptions CPUClassTableCheck.decode_{n}.' for n in names]
    return '\n'.join(out) + '\n'


BR_HEAD = r'''(** Generated by tools/cpu_class_table.py. proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.
    Design independent: the Z-level class formulas of the template route (cpu_isa_classes.py) equal the riscv-coq
    [result_word] / branch guards. No RTL is mentioned. *)
From Coq Require Import ZArith List Bool Lia.
Require Import Lang.ExtendedSV Lang.ExtendedSVBankAlignment Lang.ExtendedSVPackedROM Lang.ExtendedSVWordInvariant
 Ex.External.CV32E40PReq41Instruction Ex.External.CV32E40PReq40StateRel Ex.External.CV32E40PDataOpExecution
 Ex.External.CV32E40PISAWordInterpretation Ex.External.CV32E40PISAWordLeftShift Ex.External.CV32E40PISAWordRightShift
 Ex.External.CV32E40PBranchISACondition
 Ex.RvCore.FormalSpec Ex.RvCore.Machine coqutil.Word.Interface coqutil.Word.Properties coqutil.Word.Bitwidth
 coqutil.Map.Interface coqutil.Byte riscv.Utility.Utility riscv.Utility.MkMachineWidth.
Import ListNotations ExtendedSV ExtendedSVBankAlignment ExtendedSVPackedROM ExtendedSVWordInvariant CV32E40PReq40StateRel CV32E40PDataOpExecution CV32E40PISAWordInterpretation
 CV32E40PISAWordLeftShift CV32E40PISAWordRightShift CV32E40PBranchISACondition.
Local Open Scope Z_scope.
Module CPUClassValueBridge.
Section ISA.
Context {word : Interface.word 32} {BW : Bitwidth 32}.
Context {Registers : map.map Decode.Register word} {Mem : map.map word byte}.
Context {word_ok : word.ok word} {registers_ok : map.ok Registers} {mem_ok : map.ok Mem}.
Local Notation uw := word.unsigned.
Lemma norm_uw (x:word) : norm 32 (uw x) = uw x.
Proof. apply norm_in_range, word.unsigned_range. Qed.
Lemma uz_norm z : word.unsigned (word.of_Z z : word) = norm 32 z.
Proof. rewrite word.unsigned_of_Z. unfold word.wrap. symmetry. apply norm_mod. Qed.
Lemma bw_add (x y:word) : norm 32 (Z.add (uw x) (uw y)) = uw (word.add x y).
Proof. rewrite word.unsigned_add. unfold word.wrap. apply norm_mod. Qed.
Lemma bw_sub (x y:word) : norm 32 (Z.sub (uw x) (uw y)) = uw (word.sub x y).
Proof. rewrite word.unsigned_sub. unfold word.wrap. apply norm_mod. Qed.
Lemma bw_and (x y:word) : norm 32 (Z.land (uw x) (uw y)) = uw (word.and x y).
Proof. rewrite word.unsigned_and_nowrap. apply norm_in_range. rewrite <- word.unsigned_and_nowrap. apply word.unsigned_range. Qed.
Lemma bw_or (x y:word) : norm 32 (Z.lor (uw x) (uw y)) = uw (word.or x y).
Proof. rewrite word.unsigned_or_nowrap. apply norm_in_range. rewrite <- word.unsigned_or_nowrap. apply word.unsigned_range. Qed.
Lemma bw_xor (x y:word) : norm 32 (Z.lxor (uw x) (uw y)) = uw (word.xor x y).
Proof. rewrite word.unsigned_xor_nowrap. apply norm_in_range. rewrite <- word.unsigned_xor_nowrap. apply word.unsigned_range. Qed.
Lemma amount_range (y:word) : 0 <= uw y mod 32 < 32.
Proof. apply Z.mod_pos_bound; lia. Qed.
Lemma norm5_mod (y:word) : norm 5 (uw y) = uw y mod 32.
Proof. rewrite norm_mod. reflexivity. Qed.
Lemma bw_sll (x y:word) : norm 32 (Z.shiftl (uw x) (norm 5 (uw y))) = uw (word.slu x (word.of_Z (uw y mod 32))).
Proof. rewrite norm5_mod. rewrite <- (norm_uw x) at 1. exact (reference_left_shift x _ (amount_range y)). Qed.
Lemma bw_srl (x y:word) : norm 32 (Z.shiftr (uw x) (norm 5 (uw y))) = uw (word.sru x (word.of_Z (uw y mod 32))).
Proof. rewrite norm5_mod. rewrite <- (norm_uw x) at 1. exact (reference_logical_right_shift x _ (amount_range y)). Qed.
Lemma bw_sra (x y:word) : norm 32 (Z.shiftr (signed_value 32 (uw x)) (norm 5 (uw y))) = uw (word.srs x (word.of_Z (uw y mod 32))).
Proof. rewrite norm5_mod. exact (reference_arithmetic_right_shift x _ (amount_range y)). Qed.
Lemma bw_slt (x y:word) : norm 32 (boolz (Z.ltb (signed_value 32 (uw x)) (signed_value 32 (uw y)))) = uw (if word.lts x y then (word.of_Z 1 : word) else word.of_Z 0).
Proof. rewrite reference_signed_less. destruct (word.lts x y); rewrite uz_norm; reflexivity. Qed.
Lemma bw_sltu (x y:word) : norm 32 (boolz (Z.ltb (uw x) (uw y))) = uw (if word.ltu x y then (word.of_Z 1 : word) else word.of_Z 0).
Proof. rewrite <- reference_unsigned_less, !norm_uw. destruct (Z.ltb (uw x) (uw y)); rewrite ?uz_norm; reflexivity. Qed.
Let reg (s:FormalSpec.State) r := formal_register_word s r.
'''

BR_NAMES = {'Add': 'bw_add', 'Sub': 'bw_sub', 'Xor': 'bw_xor', 'Or': 'bw_or', 'And': 'bw_and', 'Sll': 'bw_sll',
            'Srl': 'bw_srl', 'Sra': 'bw_sra', 'Slt': 'bw_slt', 'Sltu': 'bw_sltu'}
ZF = {'Add': 'Z.add', 'Sub': 'Z.sub', 'Xor': 'Z.lxor', 'Or': 'Z.lor', 'And': 'Z.land'}


def bridge_text():
    import re
    out = [BR_HEAD]
    names = []
    for c in isa.classes():
        n, g = c['name'], c['group']
        if c['kind'] == 'branch':
            continue
        if g == 'OP':
            base = n
            f = c['value'].replace('a', '(uw (reg s rs1))', 1) if False else None
            a, b = '(uw (reg s rs1))', '(uw (reg s rs2))'
            val = re.sub(r'\b(a|b)\b', lambda m: a if m.group(1) == 'a' else b, c['value'])
            out.append(f'Lemma bridge_{n} s rd rs1 rs2 : norm 32 ({val}) = uw (result_word s (Decode.{n} rd rs1 rs2)).')
            out.append(f'Proof. cbn [result_word]. exact ({BR_NAMES[n]} _ _). Qed.')
        elif g == 'OPIMM' and n not in SHIFT_IMM:
            base = {'Addi': 'Add', 'Slti': 'Slt', 'Sltiu': 'Sltu', 'Xori': 'Xor', 'Ori': 'Or', 'Andi': 'And'}[n]
            a, b = '(uw (reg s rs))', '(norm 32 imm)'
            val = re.sub(r'\b(a|b)\b', lambda m: a if m.group(1) == 'a' else b, c['value'])
            out.append(f'Lemma bridge_{n} s rd rs imm : norm 32 ({val}) = uw (result_word s (Decode.{n} rd rs imm)).')
            out.append(f'Proof. cbn [result_word]. pose proof ({BR_NAMES[base]} (reg s rs) (word.of_Z imm)) as H. rewrite uz_norm in H. exact H. Qed.')
        elif n in SHIFT_IMM:
            base = {'Slli': 'Sll', 'Srli': 'Srl', 'Srai': 'Sra'}[n]
            val = c['value'].replace('a', '(uw (reg s rs))', 1).replace('(norm 5 b)', '(norm 5 b)')
            val = re.sub(r'\b(a)\b', '(uw (reg s rs))', c['value'])
            out.append(f'Lemma bridge_{n} s rd rs sh b : 0 <= sh < 32 -> norm 5 b = sh -> norm 32 ({val}) = uw (result_word s (Decode.{n} rd rs sh)).')
            out.append(f'Proof. intros Hr Hb. rewrite Hb. cbn [result_word]. unfold Utility.{ {"Slli":"sll","Srli":"srl","Srai":"sra"}[n] }.')
            out.append(' ' + {'Slli': 'rewrite <- (norm_uw (reg s rs)) at 1; exact (reference_left_shift _ _ Hr)',
                              'Srli': 'rewrite <- (norm_uw (reg s rs)) at 1; exact (reference_logical_right_shift _ _ Hr)',
                              'Srai': 'exact (reference_arithmetic_right_shift _ _ Hr)'}[n] + '. Qed.')
        elif n == 'Lui':
            out.append('Lemma bridge_Lui s rd imm : norm 32 (norm 32 imm) = uw (result_word s (Decode.Lui rd imm)).')
            out.append('Proof. cbn [result_word]. rewrite uz_norm. apply norm_idempotent. Qed.')
        elif n == 'Auipc':
            out.append('Lemma bridge_Auipc s rd imm : norm 32 (Z.add (uw (getPc s)) (norm 32 imm)) = uw (result_word s (Decode.Auipc rd imm)).')
            out.append('Proof. cbn [result_word]. pose proof (bw_add (word.of_Z imm) (getPc s)) as H. rewrite uz_norm in H. rewrite <- H. f_equal. lia. Qed.')
        else:
            continue
        names.append(f'bridge_{n}')
    for c in isa.classes():
        if c['kind'] != 'branch':
            continue
        n = c['name']
        a, b = '(uw x)', '(uw y)'
        cond = re.sub(r'\b(a|b)\b', lambda m: a if m.group(1) == 'a' else b, c['cond'])
        out.append(f'Lemma bridge_{n} (x y:word) rs1 rs2 imm : boolz ({cond}) = boolz (isa_branch_guard (Decode.{n} rs1 rs2 imm) x y).')
        out.append(f'Proof. cbn [isa_branch_guard Utility.reg_eqb Utility.signed_less_than Utility.ltu MachineWidth_XLEN].')
        out.append(' ' + {'Beq': 'rewrite <- word.unsigned_eqb; reflexivity', 'Bne': 'rewrite <- word.unsigned_eqb; reflexivity',
                          'Blt': 'rewrite <- reference_signed_less; reflexivity', 'Bge': 'rewrite <- reference_signed_less; reflexivity',
                          'Bltu': 'rewrite <- (word.unsigned_ltu x y); reflexivity', 'Bgeu': 'rewrite <- (word.unsigned_ltu x y); reflexivity'}[n] + '. Qed.')
        names.append(f'bridge_{n}')
    out.append('End ISA.\nEnd CPUClassValueBridge.')
    out += [f'Print Assumptions CPUClassValueBridge.{n}.' for n in names]
    return '\n'.join(out) + '\n'


INV_HEAD = r'''(** Generated by tools/cpu_class_table.py. proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.
    Design independent inverse of CPUClassTableCheck: if riscv-coq decodes a word to class C, then the table fields hold and the
    instruction arguments are the field extractions. Proved by inverting the decodeI chain of DecodeByExtension. *)
From Coq Require Import ZArith List Bool Lia.
Require Import riscv.Spec.Decode riscv.Utility.Utility riscv.Proofs.DecodeByExtension.
Import ListNotations.
Local Open Scope Z_scope.
Module CPUClassTableInverse.
Lemma dec_I w i : Decode.decode Decode.RV32I w = Decode.IInstruction i -> decodeI 32 w = i.
Proof. intro H. rewrite <- decode_seq_correct in H. unfold decode_seq in H. cbn [bitwidth] in H.
 destruct (isValidI (decodeI 32 w)); [injection H; auto|].
 cbn in H. destruct (isValidCSR (decodeCSR 32 w)); discriminate. Qed.
Ltac chain H := unfold decodeI in H;
 repeat (match type of H with context[if ?c then _ else _] => let E := fresh "E" in destruct c eqn:E; cbv iota in H; try discriminate H end).
Ltac fin :=
 match goal with E : (?x = true) |- _ =>
  repeat rewrite andb_true_iff in E; repeat rewrite orb_true_iff in E; repeat rewrite Z.eqb_eq in E;
  repeat match goal with Hc : (?a /\ ?b) |- _ => destruct Hc | Hc : (?a \/ ?b) |- _ => destruct Hc end end;
 try (match goal with Hx : (32 = 64) |- _ => exfalso; discriminate Hx end).
'''


def inverse_text():
    import re
    out = [INV_HEAD]
    names = []
    for c in isa.classes():
        n = c['name']
        a = args(c)
        # split the argument expressions (balanced parentheses at top level)
        toks, depth, cur = [], 0, ''
        for ch in a:
            if ch == '(':
                depth += 1
            if ch == ')':
                depth -= 1
            if ch == ' ' and depth == 0:
                toks.append(cur)
                cur = ''
            else:
                cur += ch
        toks.append(cur)
        vs = [f'a{i}' for i in range(len(toks))]
        eqs = ' /\\ '.join(f'{v} = {e}' for v, e in zip(vs, toks))
        h = ' /\\ '.join(hyps(c))
        qs = ' '.join(f'Q{i}' for i in range(len(toks)))
        out.append(f'Lemma invI_{n} w {" ".join(vs)} : decodeI 32 w = Decode.{n} {" ".join(vs)} -> ({eqs}) /\\ {h}.')
        k = len(toks)
        proj = lambda i: ('(eq_sym (f_equal (fun x => match x with Decode.' + n + ' ' + ' '.join(f'v{j}' for j in range(k)) + f' => v{i} | _ => 0 end) H))')
        pairs = proj(k - 1)
        for i in reversed(range(k - 1)):
            pairs = f'(conj {proj(i)} {pairs})'
        out.append(f'Proof. intro H. chain H. fin. refine (conj {pairs} _). repeat split; first [assumption|reflexivity|(exfalso; discriminate)]. Qed.')
        out.append(f'Lemma inv_{n} w {" ".join(vs)} : Decode.decode Decode.RV32I w = Decode.IInstruction (Decode.{n} {" ".join(vs)}) -> ({eqs}) /\\ {h}.')
        out.append(f'Proof. intro H. exact (invI_{n} w {" ".join(vs)} (dec_I _ _ H)). Qed.')
        names.append(f'inv_{n}')
    out.append('End CPUClassTableInverse.')
    out += [f'Print Assumptions CPUClassTableInverse.{n}.' for n in names]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(sys.argv[1]).write_text(text())
    if len(sys.argv) > 2:
        Path(sys.argv[2]).write_text(bridge_text())
    if len(sys.argv) > 3:
        Path(sys.argv[3]).write_text(inverse_text())
