#!/usr/bin/env python3
"""NERV rising-edge register steps through the NBA executor (src/Lang/ExtendedSVSymExecNb.v).
For each variant (reset input rs, reset_q rq) and register R of the sequential processes 0 (wrapper: imem_data), 1 (mem_*_q), 17 (reset_q, pc, regfile)
    norm w (read (PhaseSemantics P ev pre) R) = norm w (eval_expr driven X)
with X = executor expression simplified under  Fr = {reset = rs, reset_q = rq, stall = 0}  (facts about the DRIVEN state).
The selection facts come from the edge layers (sel_rise: reset 1; sel_rise0: reset 0).  Untrusted generator, Coq checks.
Commands: probe | gen | accept.   proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0."""
import argparse, json, re, sys, time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import cpu_tmpl_nvlib as L
ROOT = L.ROOT
CACHE = ROOT / 'scratch-nv'
VARIANTS = [(0, 0), (0, 1), (1, 0)]
PROCS = {0: [(4, 32)], 1: [(38, 1), (41, 1)], 17: [(109, 1), (45, 32), (42, 1024)]}
EDGE = 'TmplNervEdge.NervTmplEdge.NervTmplEdge'
EDGER = 'TmplNervEdgeR.NervTmplEdgeR.NervTmplEdgeR'
HDR = '''From Coq Require Import ZArith List Bool.
Require Import Lang.ExtendedSV Lang.ExtendedSVSymExec Lang.ExtendedSVFactChain Lang.ExtendedSVSymExecSym Lang.ExtendedSVEval4
 Lang.ExtendedSVRootProjection Lang.ExtendedSVProcessSlice Lang.ExtendedSVSymExecNb NervLit.NervLitAST@REQ@.
Import ListNotations ExtendedSV ExtendedSVSymExec ExtendedSVFactChain ExtendedSVSymExecSym ExtendedSVEval4 ExtendedSVRootProjection ExtendedSVProcessSlice ExtendedSVSymExecNb.
Local Open Scope Z_scope.
Notation P := NervLitAST.nerv_program.
'''


def fr(rs, rq):
    return f'[(EVar 1 16%nat, {rs}); (EVar 1 109%nat, {rq}); (EVar 1 17%nat, 0)]'


def probe():
    t = HDR.replace('@REQ@', '') + 'Set Printing Width 1000000.\n'
    for v in VARIANTS:
        t += f'Definition Fr_{v[0]}{v[1]} : Facts := {fr(*v)}.\n'
        for q, roots in PROCS.items():
            for r, w in roots:
                t += (f'Eval vm_compute in (match nbexec Fr_{v[0]}{v[1]} (statement_fuel P) (process_body (nth {q} (processes P) NervLitAST.process_0)) [] with '
                      f'Some ov => option_map (fun p => (fst p, simp4 Fr_{v[0]}{v[1]} (snd p))) (sov_lookup ov {r}%nat) | None => None end).\n')
    CACHE.mkdir(exist_ok=True)
    out = L.coqc(t, workdir=str(CACHE))
    chunks = [re.sub(r'\s+', ' ', x.split('\n     : ')[0]).strip() for x in re.split(r'(?m)^     = ', out)[1:]]
    res, p = {}, 0
    for v in VARIANTS:
        for q, roots in PROCS.items():
            for r, w in roots:
                res[f'{v[0]}{v[1]}_{r}'] = chunks[p]; p += 1
    (CACHE / 'rise_probe.json').write_text(json.dumps(res, indent=1))
    print(json.dumps(res, indent=1)[:3000])


def parse_out(s):
    if s == 'None':
        return None
    m = re.match(r'Some \((\d+)%nat, (.*)\)$', s)
    assert m, s
    return int(m.group(1)), m.group(2)


def build(module='NervTmplRise'):
    d = json.loads((CACHE / 'rise_probe.json').read_text())
    out = ['(** NERV rising-edge register steps (NBA executor). Generated by tools/cpu_tmpl_nvrise.py.',
           '    proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0. Generated. *)',
           HDR.replace('@REQ@', f' TmplNervEdge.NervTmplEdge TmplNervEdgeR.NervTmplEdgeR').rstrip(), f'Module {module}.',
           f'Module E := {EDGE}.', f'Module ER := {EDGER}.']
    names = []
    seen = set()
    for q, roots in PROCS.items():
        for r, w in roots:
            if r in seen:
                continue
            seen.add(r)
            out += [f'Lemma unw_{r} : comb_root_unwrittenb P {r}%nat = true. Proof. vm_compute; reflexivity. Qed.',
                    f'Lemma wsel_{r} : filter (writes_rootb {r}%nat) [' + ';'.join(f'NervLitAST.process_{i}' for i in range(18)) + f'] = [NervLitAST.process_{q}]. Proof. vm_compute; reflexivity. Qed.']
    for v in VARIANTS:
        rs, rq = v
        sel = 'E.sel_rise' if rs == 1 else 'ER.sel_rise0'
        hyps = (f' changed_signal ev = 0%nat -> new_value ev = 1 -> read_signal pre 0%nat = 0 -> read_signal pre 1%nat = {rs} -> E.NetWords pre -> CombLFP P seed pre ->'
                f' CombLFP P(write_signal pre(changed_signal ev)(new_value ev))(phase_driven_state P ev pre) ->')
        for q, roots in PROCS.items():
            for r, w in roots:
                po = parse_out(d[f'{rs}{rq}_{r}'])
                if po is None:
                    continue
                ww, X = po
                if ww == 0:
                    continue
                nm = f'rise_{rs}{rq}_{r}'
                out += [f'Theorem {nm} ev pre seed :{hyps} FactsHold (phase_driven_state P ev pre) {fr(rs, rq)} ->',
                        f' norm {ww} (read_signal (PhaseSemantics P ev pre) {r}%nat) = norm {ww} (eval_expr (phase_driven_state P ev pre) ({X})).',
                        'Proof. intros Hc Hv H0 H1 HW HL HD HF.',
                        f' refine (seq_nb_out2 P ev pre {r}%nat NervLitAST.process_{q} _ {ww}%nat ({X}) unw_{r} (fun H => let Hn : 0%nat = {r}%nat := eq_trans (eq_sym Hc) H in ltac:(discriminate Hn))',
                        f'   (eq_trans (hw_from_sel P pre (phase_driven_state P ev pre) {r}%nat _ ({sel} ev pre seed Hc Hv H0 H1 HW HL HD)) wsel_{r}) HF (ltac:(vm_compute; reflexivity))). Qed.']
                names.append(nm)
    # frame lemmas: roots no process writes (rom 2, reset input 1) keep their value; the clock is the event
    out += [f'End {module}.', 'Goal True. idtac "TMPL_AUDIT_BEGIN". exact I. Qed.'] + [f'Print Assumptions {module}.{n}.' for n in names]
    return '\n'.join(out) + '\n', [f'{module}.{n}' for n in names]


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['probe', 'gen', 'accept'])
    ap.add_argument('--out')
    a = ap.parse_args()
    if a.cmd == 'probe':
        probe(); sys.exit(0)
    text, exports = build()
    if a.cmd == 'gen':
        Path(a.out).write_text(text); print(len(text.splitlines()), 'lines'); sys.exit(0)
    import cpu_tmpl_accept as acc
    lp = [('experiments/framework/generated/nerv-lit', 'NervLit')]
    prov = [dict(namespace='TmplNervEdge', directory=str((ROOT / 'results/r-tmpl-nerv-edge-20261104-a1').resolve())),
            dict(namespace='TmplNervEdgeR', directory=str((ROOT / 'results/r-tmpl-nerv-edger-20261104-a2').resolve()))]
    r = acc.accept(a.out, 'TmplNervRise', 'NervTmplRise', text, exports, lp, providers=prov, factcheck=False, extra=dict(generator='tools/cpu_tmpl_nvrise.py', design='nerv'))
    print(json.dumps({k: v for k, v in r.items() if k != 'info'}, indent=1)); sys.exit(0 if r.get('coqc_accepted') else 1)
