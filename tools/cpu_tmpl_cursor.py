"""Cursor layer (goal_cursor of the template D step): PC sequencing invariant over a whole actual_cycle, the per-class
jump/branch/link cases generated from the ISA class table, and the committing-cycle cursor theorem.

Generated (role- and class-table-parameterised):
  * wire equations of the operand/immediate field wires (S1PTR, S2PTR, SIMM),
  * one `dec_<Class>` lemma per class of tools/cpu_isa_classes.py: decode of the slot word to the class constructor
    (CPUClassTableInverse.inv_<Class>) -> prem_<Class> (DarkTmplInv.inv_prem_<Class>) -> the class's controller facts
    (DarkTmplControls.<Class>_controls), projected to the pc-sequencing outputs of the class kind
    (dataop: JREQ = 0; jal: JREQ = 1, JVAL = PC + SIMM; jalr: JREQ = 1, JVAL from operand A + SIMM;
     branch: JREQ = BMUX, JVAL = PC + SIMM, BMUX = condition of the class on operands A and B),
  * the per-group SIMM lemma (DarkTmplImm.isa_simm_<Group>) for the groups that appear in jump kinds,
  * the dispatch lists used by the hand-written core framework/template-sources/DarkTmplCursorCore.v.in.
Everything is checked by Coq; no RTL value is used as an expectation.
"""
