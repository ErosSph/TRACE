ARITY = {'dataop3': 3, 'dataop2': 2}


def ctor_args(c):
    n = c['name']
    if n in ('Lui', 'Auipc', 'Jal'):
        return 2
    return 3


INV_FILE = Path('src/Ex/External/CPUClassTableInverse.v')


def inv_tail(name):
    """Bit-slice conjuncts (start,end,value) at the end of inv_<Class>, in order (parsed from the generic library)."""
    for line in INV_FILE.read_text().splitlines():
        m = re.match(r'Lemma inv_' + name + r' .*?\) /\\ (bitSlice .*)\.$', line)
        if m:
            return [(int(a), int(b), int(v)) for a, b, v in re.findall(r'bitSlice w (\d+) (\d+) = (\d+)', m.group(1))]
    raise KeyError(name)


def prem_args(c, tail):
    """Pattern naming the tail conjuncts of inv_<Class>, the rewriting script, and the arguments of inv_prem_<Class>."""
    tail = inv_tail(c['name'])
    names = [f'H{a}_{b}' for a, b, _ in tail]
    lines, args = [], []
    slices = {(a, b): n for (a, b, _), n in zip(tail, names)}
    lines.append(f'rewrite bs_0_7 in {slices[(0, 7)]}.')
    args.append(slices[(0, 7)])
    if c['funct3'] is not None:
        lines.append(f'rewrite bs_12_15 in {slices[(12, 15)]}.')
        args.append(slices[(12, 15)])
    if c['funct7'] is not None:
        if (25, 32) in slices:
            lines.append(f'rewrite bs_25_32 in {slices[(25, 32)]}.')
            args.append(slices[(25, 32)])
        else:
            lines.append(('assert (Hf7 : norm 7 (Z.shiftr (norm 32 (read_signal d @WORD@%nat)) 25) = FF7) by (rewrite bs_shift7, ' + slices[(26, 32)] + ', ' + slices[(25, 26)] + '; reflexivity).').replace('FF7', str(c['funct7'])))
            args.append('Hf7')
    return names, lines, args


def cond_text(g, c, a, b):
    return ctl.sub(c['cond'], a, b, '', '')


def dec_lemma(g, c, ids):
    n = c['name']
    na = ctor_args(c)
    binders = ' '.join(f'a{i}' for i in range(na))
    names, lines, args = prem_args(c, None)
    inv = f'Cls.inv_{n} ' + ' '.join(['_'] * (na + 1)) + ' '
    pat = '[_ [' + ' [' .join(names) + ']' * 0 + ']' if False else None
    # destructuring pattern: (fields) /\ Hop /\ Hf3 /\ ...
    pat = '[_ ' + ''.join(f'[{x} ' for x in names[:-1]) + names[-1] + ']' * (len(names) - 1) + ']'
    k = c['kind']
    d = 'd'
    rd = lambda i: f'(read_signal {d} {i}%nat)'
    if k == 'dataop':
        concl = f'norm 1 {rd(ids["jreq"])} = 0'
        proj = '(_&_&_&H84&_)'
        fin = 'exact H84.'
    elif k == 'jal':
        concl = f'norm 1 {rd(ids["jreq"])} = 1 /\\ norm 32 {rd(ids["jval"])} = norm 32 (norm 32 {rd(ids["pc"])} + norm 32 {rd(ids["imm"])})'
        proj = '(_&_&_&H84&H85&_)'
        fin = 'split; assumption.'
    elif k == 'jalr':
        concl = (f'norm 1 {rd(ids["jreq"])} = 1 /\\ norm 32 {rd(ids["jval"])} = norm 32 (Z.shiftl (Z.shiftr (norm 32 (norm 32 {rd(ids["a"])} + norm 32 {rd(ids["imm"])})) 1) 1)')
        proj = '(_&_&_&H84&H85&_)'
        fin = 'split; assumption.'
    else:
        a = f'(norm 32 {rd(ids["a"])})'
        b = f'(norm 32 {rd(ids["b"])})'
        cond = ctl.sub(c['cond'], a, b, '', '')
        concl = (f'norm 1 {rd(ids["jreq"])} = norm 1 {rd(ids["bmux"])} /\\ norm 32 {rd(ids["jval"])} = norm 32 (norm 32 {rd(ids["pc"])} + norm 32 {rd(ids["imm"])}) /\\ '
                 f'norm 1 {rd(ids["bmux"])} = boolz ({cond})')
        proj = '(_&_&_&H84&H85&H82&_)'
        fin = 'repeat split; assumption.'
    ctor = f'Decode.{n} ' + ' '.join(f'a{i}' for i in range(na))
    return [
        f'Lemma dec_{n} seed d : CombLFP P seed d -> base d -> Inv.CoherentFields d ->',
        f' forall {binders}, Decode.decode Decode.RV32I (norm 32 (read_signal d @WORD@%nat)) = Decode.IInstruction ({ctor}) ->',
        f' {concl}.',
        f'Proof. intros HL Hb HC {binders} Hd.',
        f' destruct ({inv}Hd) as {pat}.',
        ' ' + ' '.join(lines),
        f' pose proof (Inv.inv_prem_{n} seed d HL Hb HC {" ".join(args)}) as Hp.',
        f' destruct (Ctl.{n}_controls seed d HL Hp) as {proj}. {fin} Qed.']


def groups_of_jumps(classes):
    return sorted({c['group'] for c in classes if c['kind'] in ('jal', 'jalr', 'branch')},
                  key=lambda g: ['JAL', 'JALR', 'BRANCH'].index(g))


def simm_lemma(gname, opcode, ids, coh_pat, coh_name):
    return [
        f'Lemma simm_{gname} seed d : CombLFP P seed d -> Inv.CoherentFields d -> norm 7 (norm 32 (read_signal d @WORD@%nat)) = {opcode} ->',
        f' norm 32 (read_signal d @SIMM@%nat) = norm 32 (Shp.isa_imm_{ {"JAL":"J","JALR":"I","BRANCH":"B"}[gname] } (norm 32 (read_signal d @WORD@%nat))).',
        'Proof. intros HL HC Hop. rewrite (eq_w@SIMM@ seed d HL). unfold orig_w@SIMM@. cbn [eval_expr]. rewrite norm_idempotent.',
        f' destruct HC as {coh_pat}. rewrite {coh_name}. exact (Imm.isa_simm_{gname} d Hop). Qed.']


def brx_lemmas(classes, ids):
    """Per branch class: the RTL jump request / target in ISA terms (guard of the decoded instruction on the architectural registers)."""
    out = []
    for c in classes:
        if c['kind'] != 'branch':
            continue
        n = c['name']
        out += [
            f'Lemma brx_{n} seed d (f : FormalSpec.State) : CombLFP P seed d -> base d -> Inv.CoherentFields d -> RF.RFZero (read_signal d @BANK@%nat) f ->',
            f' forall a0 a1 a2, Decode.decode Decode.RV32I (norm 32 (read_signal d @WORD@%nat)) = Decode.IInstruction (Decode.{n} a0 a1 a2) ->',
            f' norm 1 (read_signal d @JREQ@%nat) = boolz (CV32E40PBranchISACondition.CV32E40PBranchISACondition.isa_branch_guard (Decode.{n} a0 a1 a2) (FRW f a0) (FRW f a1)) /\\',
            ' norm 32 (read_signal d @JVAL@%nat) = norm 32 (norm 32 (read_signal d @PC@%nat) + norm 32 a2).',
            'Proof. intros HL Hb HC HRF a0 a1 a2 Hd.',
            f' destruct (dec_{n} seed d HL Hb HC _ _ _ Hd) as [H84 [H85 H82]].',
            f' destruct (Cls.inv_{n} _ _ _ _ Hd) as [[Hr1 [Hr2 Himm]] [Hopc _]].',
            " assert (Himm' : a2 = Shp.isa_imm_B (norm 32 (read_signal d @WORD@%nat))) by (unfold Shp.isa_imm_B; exact Himm).",
            ' rewrite bs_0_7 in Hopc. pose proof (simm_BRANCH seed d HL HC Hopc) as H50.',
            ' rewrite (RF.operand_isa_@A@ _ _ f HL HRF), (s1_field _ _ HL), <- Hr1, fw_view in H82.',
            ' rewrite (RF.operand_isa_@B@ _ _ f HL HRF), (s2_field _ _ HL), <- Hr2, fw_view in H82.',
            f' split; [rewrite H84, H82; apply CPUClassValueBridge.CPUClassValueBridge.bridge_{n}|].',
            " rewrite H85, H50, <- Himm'. reflexivity. Qed."]
    return out


def gen_block(design):
    """Generated Coq text: field wire equations, per-group SIMM lemmas, per-class dec lemmas, dispatch lists."""
    import cpu_tmpl_inv as inv
    g = ctl.Gen(design, 'DarkTmplCursor')
    ids = g.id
    ast, pr, tr = g.ast, g.pr, g.tr
    classes = isa.classes()
    c = pr['controller']
    s1, s2 = c['rs1']['id'], c['rs2']['id']
    for r in (s1, s2, ids['imm']):
        g.wire_eq(r)
    fields, _ = inv.captured_fields(ast, pr)
    regs = [R for R, _, _ in fields]
    cpat = f'C{regs[-1]}'
    for R in reversed(regs[:-1]):
        cpat = f'[C{R} {cpat}]' if False else f'C{R} {cpat}'
    cpat = '[' + ' ['.join(f'C{R}' for R in regs[:-1]) + ' C%d' % regs[-1] + ']' * (len(regs) - 1)
    simm_src = ast.comb[ids['imm']]['rhs']
    assert simm_src[0] == 'EVar'
    simm_reg = simm_src[2]
    out = list(g.head)
    for grp, opc in (('JAL', isa.OPS['JAL']), ('JALR', isa.OPS['JALR']), ('BRANCH', isa.OPS['BRANCH'])):
        out += simm_lemma(grp, opc, ids, cpat, f'C{simm_reg}')
    for cl in classes:
        out += dec_lemma(g, cl, ids)
    dataops = [cl['name'] for cl in classes if cl['kind'] == 'dataop']
    dispatch = ' | '.join(f'exact (dec_{n} seed d HL Hb HC _ _ _ Hd)' if n not in ('Lui', 'Auipc') else f'exact (dec_{n} seed d HL Hb HC _ _ Hd)' for n in dataops)
    out += ['Lemma dataop_jreq0 seed d i : CombLFP P seed d -> base d -> Inv.CoherentFields d ->',
            ' Decode.decode Decode.RV32I (norm 32 (read_signal d @WORD@%nat)) = Decode.IInstruction i -> CV32E40PDataOpProgramScope.CV32E40PDataOpProgramScope.DataOp21 i ->',
            ' norm 1 (read_signal d @JREQ@%nat) = 0.',
            'Proof. intros HL Hb HC Hd H. destruct i; cbn [CV32E40PDataOpProgramScope.CV32E40PDataOpProgramScope.DataOp21 CV32E40PDataOpProgramScope.CV32E40PDataOpProgramScope.dataop21b] in H; try discriminate.',
            ' all: first [ ' + dispatch + ' ]. Qed.']
    ids2 = dict(ids)
    alts = []
    for cl in classes:
        if cl['kind'] == 'branch':
            alts.append(f'(destruct (brx_{cl["name"]} _ _ f HLd Hb HCd HRFd _ _ _ Hd) as [B1 B2]; rewrite (driven_read (rtl s) @PC@%nat comb_unw_@PC@ ltac:(discriminate)) in B2; exact (fin_branch image s f _ _ _ _ HE HX HF Hpcs Hc1 Hc2 eq_refl eq_refl eq_refl B1 B2))')
    ids2['brdisp'] = 'destruct op; [ ' + ' | '.join(alts) + ' ].'
    ids2['brx'] = '\n'.join(brx_lemmas(classes, ids))
    ids2.update(word=pr['fetch_slot']['word']['id'], s1=s1, s2=s2, bank=pr['rf_write']['bank']['id'])
    return '\n'.join(out), ids2


