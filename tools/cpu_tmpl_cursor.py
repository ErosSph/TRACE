def text(design, module):
    blk, ids = gen_block(design)
    core = PR.Params(design).core('TmplCursorCore.v.in')
    sub = {'@WORD@': ids['word'], '@SIMM@': ids['imm'], '@JREQ@': ids['jreq'], '@JVAL@': ids['jval'], '@PC@': ids['pc'],
           '@BANK@': ids['bank'], '@A@': ids['a'], '@B@': ids['b']}
    brx, brd = ids['brx'], ids['brdisp']
    for k, v in sub.items():
        blk, brx, brd = blk.replace(k, str(v)), brx.replace(k, str(v)), brd.replace(k, str(v))
    core = core.replace('(*@GEN@*)', blk).replace('(*@BRX@*)', brx).replace('(*@BRDISP@*)', brd)
    body = HDR.replace('@REQUIRES@', REQ) + 'Module %s.\n' % module + core + 'End %s.\n' % module
    names = ['pcseq_reset', 'pcseq_step', 'cursor_inv_reset', 'cursor_inv_step', 'commit_cursor', 'cursor_silent', 'cursor_next']
    names += ['simm_' + g for g in ('JAL', 'JALR', 'BRANCH')]
    names += ['dec_' + c['name'] for c in isa.classes()]
    names += ['brx_' + c['name'] for c in isa.classes() if c['kind'] == 'branch']
    body += ''.join(f'Print Assumptions {module}.{n}.\n' for n in names)
    return body, [f'{module}.{n}' for n in names]


