#!/usr/bin/env python3
"""Generic CLOSURE stage generator of the template route (INV/rank/cycle/D step -> final infinite ITree refinement).

Input : framework/closure-schemas/<design>.json   (the clause SCHEMA; see proof-optimization-log/20261104-stage-closure.md)
Output: one Coq module in which every goal of the generic staged obligations (tools/cpu_pipeline_skeleton.py) is discharged by ONE
        generated proof pattern per goal, from the lower-layer lemma shapes named in the schema (`lo`, `ids`, `boot`).
Shapes: `counter` (N=0 commit-counter pipelines, DarkRISCV-like), `staged` (stage-relation pipelines with a stored valid bit, Bzeeno-like)
        and `state_inv` (Runtime = the RTL state, joint INV = boot phases | operating INV, Steel-like; added by the closure agent, claude-opus-5-5).
Modes : --out F            write the module
        --regress          generate and compare with the accepted reference source (same_statement regression)
        --out D --accept   run the double-0 gate (tools/cpu_tmpl_accept.py)
Untrusted generator. proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import cpu_pipeline_skeleton as sk

TPL = ROOT / 'tools' / 'closure_templates'
SCHEMAS = ROOT / 'framework' / 'closure-schemas'
REQUIRED = {
    'counter': ['stages', 'valid', 'pending_view', 'front', 'boot', 'observer', 'rank', 'lo', 'skeleton'],
    'derived': ['stages', 'valid', 'pending_view', 'front', 'boot', 'observer', 'rank', 'lo', 'needs'],
    'staged': ['stages', 'valid', 'pending_view', 'front', 'boot', 'observer', 'rank', 'lo', 'ids', 'skeleton'],
    'state_inv': ['stages', 'valid', 'boot', 'operating', 'observer', 'rank', 'target', 'imports', 'aliases', 'runtime', 'token_expr'],
}


def load(design):
    s = json.loads((SCHEMAS / f'{design}.json').read_text())
    check(s)
    return s


def check(s):
    miss = [k for k in REQUIRED[s['shape']] if k not in s]
    if miss:
        raise SystemExit(f'schema {s.get("design")}: missing clauses {miss}')
    if s['stages']['count'] != len(s['stages']['names']):
        raise SystemExit('schema: stages.count != len(stages.names)')


def lookup(s, path):
    v = s
    for k in path.split('.'):
        v = v[k]
    return str(v)


def fill(text, s, extra=None):
    """@{a.b} -> schema value (extra dict first)."""
    def f(m):
        k = m.group(1)
        if extra and k in extra:
            return extra[k]
        return lookup(s, k)
    return re.sub(r'@\{([A-Za-z0-9_.]+)\}', f, text)


def fill_json(obj, s):
    return json.loads(fill(json.dumps(obj), s)) if False else _walk(obj, s)


def _walk(o, s):
    if isinstance(o, str):
        return fill(o, s)
    if isinstance(o, list):
        return [_walk(x, s) for x in o]
    if isinstance(o, dict):
        return {k: _walk(v, s) for k, v in o.items()}
    return o


# ---------------------------------------------------------------- counter shape (DarkRISCV-like)
def committing(v):
    """valid clause -> Coq bool over the runtime state s.  counter_zero: register == 0; bool_expr: arbitrary Coq bool text (`coq`) over s."""
    if v['kind'] == 'counter_zero':
        return f"Z.eqb(norm {v['width']}(read_signal(rtl s){v['reg']}%nat))0"
    if v['kind'] == 'bool_expr':
        return v['coq']
    raise SystemExit(f"valid.kind {v['kind']} not supported by the counter shape")


def counter_text(s, params_render):
    sc = _walk(s['skeleton'], s)
    lo, v, pv, fr = s['lo'], s['valid'], s['pending_view'], s['front']
    tok = s['stages']['token']
    bank = pv['bank']
    arch = ' /\\ '.join(c.replace('{bank}', str(bank)) for c in pv['arch_clauses'])
    front = (f"{lo['inv']}.CoherentFields(rtl s) /\\ {lo['cyc']}.env_ok s /\\ {lo['cursor']}.cursor_inv image s"
             + ''.join(' /\\ ' + c for c in fr['cursor_clauses']))
    P = s['binders']
    sc['module_prelude'] = [
        f"Module ARCH := {lo['arch']}.",
        f"Definition tmpl_arch{P}(s:Runtime)(isa:FormalSpec.State):Prop:=ARCH.tmpl_arch image HC s isa.",
        f"Definition tmpl_front(image:list Z)(s:Runtime)(f:FormalSpec.State):Prop:={front}.",
        f"Definition tmpl_committing(s:Runtime):bool:={committing(v)}.",
        f"Definition tmpl_plan_shape(s:Runtime):Shape(Token:=Z):=if tmpl_committing s then Advance(Some(norm {tok['width']}(read_signal(rtl s){tok['reg']}%nat)))else Advance None.",
        "Definition tmpl_plan_next(s:Runtime)(_ f:FormalSpec.State):FormalSpec.State:=if tmpl_committing s then snd(FormalSpec.run1 f)else f.",
        f"Definition tmpl_rank(s:Runtime)(_:FormalSpec.State):nat:={lo['cyc']}.tmpl_rank s.",
    ]
    sc['proof_author'] = s['provenance']['proof_author']
    body = sk.skeleton(sc).replace('Generated by tools/cpu_pipeline_skeleton.py; do not edit by hand.',
                                   'Generated by tools/cpu_tmpl_closure.py via tools/cpu_pipeline_skeleton.py; do not edit by hand.')
    extra = fill((TPL / 'counter_extra.v.tmpl').read_text(), s, dict(P=P, A=s['args']))
    module = s['module']
    end = f'End {module}.\n'
    k = body.rindex(end)
    body = (body[:k] + extra + end + f'Print Assumptions {module}.boot_proved.\nPrint Assumptions {module}.startup_proved.\n'
            f'Print Assumptions {module}.refinement.\n' + body[k + len(end):])
    exports = [f'{module}.assembled', f'{module}.boot_proved', f'{module}.startup_proved', f'{module}.refinement']
    return params_render(body), exports


# ---------------------------------------------------------------- state_inv shape (Steel-like)
def _intro(n):
    p = '[index HO]'
    for _ in range(n):
        p = '[[-> ->]|' + p + ']'
    return p


def state_inv_text(s):
    """Runtime = RTL state; INV = boot phase 1 | ... | boot phase n | exists index, Op; the D step template is
    tools/closure_templates/state_inv_step.v.tmpl; the boot arms of inv_silent / inv_commit are generated from boot.phases."""
    ph, op, tg = s['boot']['phases'], s['operating'], s['target']
    entry = s['boot']['op_entry']
    n = len(ph)
    inv = ' \\/ '.join(f'(s = {q["state"]} image /\\ f = initial image)' for q in ph) + f' \\/ exists index, {op["inv"]} image s f index.'
    inv = inv.replace('\\\\', '\\')
    sil = [f'Proof. intros {_intro(n)} Hc; unfold tmpl_rank.']
    for k, q in enumerate(ph):
        if k + 1 < n:
            nx = ph[k + 1]
            sil += [f' - split; [{"right; " * (k + 1)}left; split; reflexivity|]. change (actual_cycle image ({q["state"]} image)) with ({nx["state"]} image).',
                    f'   rewrite {nx["rank"]}, {q["rank"]}. lia.']
        else:
            sil += [f' - split; [{"right; " * n}exists 0%nat; exact ({entry["lemma"]} image HC)|]. change (actual_cycle image ({q["state"]} image)) with ({entry["state"]} image).',
                    f'   rewrite ({entry["rank"]} image _ _ _ ({entry["lemma"]} image HC)), {q["rank"]}. lia.']
    inj = 'right; ' * n
    if 'silent' in op:   # pulse shape: the operating INV has silent cycles of its own (junk slots), with a strictly decreasing rank
        sil += [f' - destruct ({op["silent"]} image HC s f index HO Hc) as [HO\' Hr]. split; [{inj}exists index; exact HO\'|exact Hr]. Qed.']
    else:
        da, db = s['valid']['driven_alias']
        sil += [f' - exfalso. destruct ({op["step"]} image HC s f index HO) as [y [index\' [_ [Hk _]]]]. unfold tmpl_committing in Hc.',
                f'   change ({da}) with ({db}) in Hc. congruence. Qed.']
    com = [f'Proof. intros {_intro(n)} Hc.']
    for q in ph:
        com.append(f' - exfalso. rewrite (silent_obs _ ({q["observe"]} image)) in Hc. discriminate.')
    if 'commit' in op:   # pulse shape: commit lemma takes the commit bit (shape: exists y index', run1 /\ token = pc /\ Op post)
        com += [f' - destruct ({op["commit"]} image HC s f index HO Hc) as [y [index\' [HR [Ht HO\']]]].']
    else:
        com += [f' - destruct ({op["step"]} image HC s f index HO) as [y [index\' [HR [_ [Ht HO\']]]]].']
    com += [
            "   exists y. split; [exact HR|]. split; [exact Ht|]. right; right. exists index'. exact HO'. Qed."]
    if n != 2:
        com[-1] = com[-1].replace('right; right.', 'right; ' * n)
    extra = dict(doc=s['doc'], ast=s['ast'], imports=' '.join(s['imports']), module=s['module'],
                 aliases='\n'.join(f'Module {k} := {v}.' for k, v in s['aliases'].items()), runtime=s['runtime'],
                 initial=tg['initial'], reset=tg['reset'], cycle=tg['cycle'], observe=tg['observe'], inv_body=inv,
                 commit=s['valid']['coq'], token_w=str(s['stages']['token']['width']), token=s['token_expr'], rank=s['rank']['expr'],
                 silent_proof='\n'.join(sil), commit_proof='\n'.join(com))
    body = fill((TPL / (s.get('template', 'state_inv_step') + '.v.tmpl')).read_text(), s, extra)   # template variant: additive schema key
    M = s['module']
    exports = [f'{M}.refinement', f'{M}.assembled', f'{M}.inv_commit', f'{M}.inv_silent']
    return body, exports


# ---------------------------------------------------------------- staged shape (Bzeeno-like)
def chain(lo_reset, ids):
    t = f'({lo_reset}.boot_reset_{ids[-2]} img) ({lo_reset}.boot_reset_{ids[-1]} img)'
    out = f'(conj ({lo_reset}.boot_reset_{ids[-2]} img) ({lo_reset}.boot_reset_{ids[-1]} img))'
    for i in reversed(ids[:-2]):
        out = f'(conj ({lo_reset}.boot_reset_{i} img) {out})'
    return out


def staged_text(s):
    lo, ids, b = s['lo'], s['ids'], s['boot']
    sc = _walk(s['skeleton'], s)
    sc['proof_author'] = s['provenance']['proof_author']
    R = lo['reset']
    vs = b['valid_ids']
    x = dict(
        valid_asserts=' '.join(f'assert (H{i} := {R}.boot_valid_{i} img).' for i in vs),
        valid_rw=', '.join(f'H{i}' for i in vs), v0=str(vs[0]),
        chain_a=chain(R, b['chain_a']), chain_b=chain(R, b['chain_b']),
        pair=f"(conj ({R}.boot_reset_{b['pair'][0]} img) ({R}.boot_reset_{b['pair'][1]} img))",
        tail=str(b['tail']), pc=str(b['pc']))
    # skeleton + proved / rank pieces (step a3 layout)
    body = sk.skeleton(sc)
    T = lambda n: fill((TPL / f'staged_{n}.v.tmpl').read_text(), s, {'x.' + k: v for k, v in x.items()}).replace(
        'BzeenoLoadUseJalASTConfigured3122be4a95.bzeeno_load_use_jal_program', s['prog'])
    marker = '(** All goals together give the refinement from actual reset. *)'
    k = body.index(marker)
    body = body[:k] + T('proved') + T('rank') + '\n' + body[k:]
    M = s['module']
    pa = f'Print Assumptions {M}.assembled.'
    body = body.replace(pa, 'Goal True. idtac "TMPL_AUDIT_BEGIN". exact I. Qed.\n' + pa + ''.join(
        f'\nPrint Assumptions {M}.{n}.' for n in ['startup_proved', 'observer_proved', 'shape_proved', 'rank_proved', 'boot_proved']))
    # final assembly (step a4 layout): design/plan aliases to the Defs module, transport/admission/front/arch from lower layers
    D = lo['defs']
    extra_req = ' '.join(fill(r, s) for r in s['extra_require'])
    head = ' '.join(fill(r, s) for r in s['extra_require'] if not r.startswith(('Ex.', 'Lang.')))
    pre = ' '.join(r for r in map(lambda r: fill(r, s), s['extra_require']) if r.startswith(('Ex.', 'Lang.')))
    EXTRA_REQ = f'Require Import {pre}\n {head}.\n'
    P = sc['params']
    ALIAS = (f'Definition design{P}:={D}.design words HC.\nDefinition plan_shape{P}:={D}.plan_shape words HC.\n'
             f'Definition plan_next{P}:={D}.plan_next words HC.\n')
    a = body.index('Definition design(')
    b2 = body.index('Definition goal_shape(')
    body = body[:a] + ALIAS + body[b2:]
    body = body.replace('Import ListNotations CPUGeneratedJointTemplate', EXTRA_REQ + 'Import ListNotations CPUGeneratedJointTemplate', 1)
    k = body.index(marker)
    body = body[:k] + T('transport') + '\n' + body[k:]
    e = body.index('End Skeleton.')
    body = body[:e] + T('final') + body[e:]
    pa = body.index(pa)
    body = body[:pa] + f'Print Assumptions {M}.template_checked_program_infinite_itree.\nPrint Assumptions {M}.same_statement_as_reference.\n'
    body = body.replace('cbn[design ', f'cbn[design {D}.design ').replace('cbn [design ', f'cbn [design {D}.design ')
    body = body.replace('unfold plan_shape.', f'unfold plan_shape, {D}.plan_shape.').replace('unfold plan_shape,', f'unfold plan_shape, {D}.plan_shape,')
    body = body.replace(f'{D}.plan_shape, {D}.plan_shape', f'{D}.plan_shape')
    return body, [f'{M}.template_checked_program_infinite_itree', f'{M}.same_statement_as_reference']


CONTRACT = '''Lemma shapes the closure generator consumes from the lower layers (driver/lift), per design, with R = Runtime state, F = ISA state:
 inv      : stages R (stage list), arch_rel R F, front_rel R F, stage_rel (or Struct); environment predicate Env R and clock boundary
 shape    : Env R -> one-step stage list = shape_post (plan_shape R) (stages R)       (valid predicate decides Advance (Some tok) / Advance None)
 observer : Env R -> actual_observe R = observe (shape_retiring (plan_shape R) (stages R))     (valid bit/expr and token register)
 cycle    : Env R -> Env (cycle R), coherent fields / clock boundary preserved
 boot     : inv at the actual reset (RF zero, struct facts, token register = ISA pc 0)
 rank     : silent observer -> rank (cycle R) < rank R
 transport/admission/front/arch : per class lift (CPUClassValueBridge / CPUJumpFamilyPostShape / CPUISARegView): retired RF view = ISA regs, pending write visible only in the pending view,
            run1 total on check_program (checked_run1_total), cursor/pc update'''


def needs(design):
    s = json.loads((SCHEMAS / f'{design}.json').read_text())
    print(CONTRACT)
    print('design', design, 'shape', s['shape'], 'status', s.get('status', 'generated'))
    for k, v in s.get('lo', {}).items():
        print(f'  lo.{k} = {v}')
    for n in s.get('needs', []):
        print('  OPEN:', n)


def generate(design):
    s = load(design)
    if s['shape'] == 'derived':
        raise SystemExit(f'{design}: lower layers pending (status {s.get("status")}); run --needs')
    if s['shape'] == 'state_inv':
        return s, *state_inv_text(s)
    if s['shape'] == 'counter':
        import cpu_tmpl_params as PR
        return s, *counter_text(s, PR.Params(s['design_for_params']).render)
    return s, *staged_text(s)


def run_layers(design):
    """Regress the lower-layer modules (INV, cycle, cursor, arch, valid, rank, reset) that the schema names: generator output must equal the accepted source."""
    import subprocess, tempfile
    s = load(design)
    ok = True
    for L in s.get('layers', []):
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / (L['module'] + '.v')
            r = subprocess.run([sys.executable] + [a.replace('{out}', str(out)) for a in L['argv']], cwd=ROOT, capture_output=True, text=True)
            ref = ROOT / L['ref'] / (L['module'] + '.v')
            strip = lambda t: t.replace('Goal True. idtac "TMPL_AUDIT_BEGIN". exact I. Qed.\n', '')
            same = r.returncode == 0 and strip(out.read_text()) == strip(ref.read_text())
        ok &= same
        print(json.dumps(dict(design=design, layer=L['name'], module=L['module'], reference=L['ref'], identical_source=same)))
    return ok


def regress(design):
    s, body, _ = generate(design)
    ref = ROOT / s['reference']['result'] / s['reference']['file']
    r = ref.read_text()
    norm = lambda t: t.replace('Goal True. idtac "TMPL_AUDIT_BEGIN". exact I. Qed.\n', '').replace('tools/cpu_tmpl_dstep.py via', 'tools/cpu_tmpl_closure.py via')
    ok = norm(body) == norm(r)
    print(json.dumps(dict(design=design, reference=str(ref.relative_to(ROOT)), identical_source=ok, generated_lines=len(body.splitlines()))))
    return ok


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('--design', required=True)
    ap.add_argument('--out')
    ap.add_argument('--regress', action='store_true')
    ap.add_argument('--needs', action='store_true')
    ap.add_argument('--layers', action='store_true', help='regress the lower-layer generators named in the schema')
    ap.add_argument('--accept', action='store_true')
    ap.add_argument('--provider', action='append', default=[])
    ap.add_argument('--providers-from', action='store_true', help='reuse the lower-layer providers.json of the schema reference result')
    a = ap.parse_args()
    if a.needs:
        needs(a.design)
        sys.exit(0)
    if a.layers:
        sys.exit(0 if run_layers(a.design) else 1)
    if a.regress:
        sys.exit(0 if regress(a.design) else 1)
    s, body, exports = generate(a.design)
    if not a.accept:
        Path(a.out).write_text(body)
        print(a.out, len(body.splitlines()))
        sys.exit(0)
    import cpu_tmpl_accept as acc
    lp = [tuple(x) for x in s.get('extra_loadpaths', [])]
    prov = [dict(namespace=x.split('=')[0], directory=str(Path(x.split('=')[1]).resolve())) for x in a.provider]
    if a.providers_from:
        prov += json.loads((ROOT / s['reference']['result'] / 'providers.json').read_text())
    r = acc.accept(a.out, s['namespace'], s['module'], body, exports, lp, providers=prov,
                   extra=dict(generator='tools/cpu_tmpl_closure.py', design=s['design'], schema=f'framework/closure-schemas/{s["design"]}.json', proof_author=s['provenance']['proof_author']))
    print(json.dumps(r, indent=1))
    sys.exit(0 if (r['accepted'] or r.get('coqc_accepted')) else 1)
