#!/usr/bin/env python3
"""Driven-state LFP convergence for any design whose combinational processes are blocking-only (generalized rule).

Emits a module that instantiates src/Lang/ExtendedSVBitStabilityNoLatch.v (known-bit certificate, all states) for the
design's AST, with the smallest round count N <= lfp_fuel that the mask iteration needs (found here by an
untrusted Python search over N = 1..lfp_fuel using Coq's own vm_compute through the module itself: the module
states `all_known (Kiter0 P N)` and Coq checks it).  Result for every state of the right length:
  comb_round P (comb_iter P N seed) = comb_iter P N seed,   and the driven state / both settles of PhaseSemantics are CombLFP.
proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.
"""
import argparse
import json
import sys
from pathlib import Path
import cpu_tmpl_ast as T

PROFILE = Path('framework/auto-contract-profiles')

TEXT = r"""(** @DESIGN@: all-states combinational convergence (bit-mask certificate, latch-free) and the driven-state / settle LFP facts.
    Generated by tools/cpu_tmpl_lfpnl.py.  proof_author: @AUTHOR@; external_llm_api_calls=0. *)
From Coq Require Import ZArith List Bool.
Require Import Lang.ExtendedSV Lang.ExtendedSVBitStability Lang.ExtendedSVBitStabilityNoLatch Lang.ExtendedSVPhaseLength @AST@.
Import ListNotations ExtendedSV ExtendedSVBitStability ExtendedSVBitStabilityNoLatch ExtendedSVPhaseLength.
Module @MOD@.
Notation P := @PROG@.
Notation NSIG := @NSIG@%nat.
Lemma cert_ok : cert0_b P = true. Proof. vm_compute; reflexivity. Qed.
Lemma wb_ok : WB P NSIG. Proof. apply wb_check_sound. vm_compute; reflexivity. Qed.
Lemma fuel_ok : lfp_fuel P = @N@%nat. Proof. vm_compute; reflexivity. Qed.
Lemma known_ok : all_known (Kiter0 P @N@) (signal_count P) = true. Proof. vm_compute; reflexivity. Qed.
Lemma count_ok : signal_count P = NSIG. Proof. vm_compute; reflexivity. Qed.

(** for EVERY state of the right length, the candidate of the program's own fuel is a combinational fixed point *)
Theorem stable : forall seed, length seed = NSIG ->
  comb_round P (lfp_candidate P seed) = lfp_candidate P seed.
Proof.
  intros seed Hl. unfold lfp_candidate. rewrite fuel_ok.
  apply (comb_stable0_b P @N@ cert_ok known_ok). rewrite count_ok. exact Hl.
Qed.

Theorem lfp_of_seed : forall seed, length seed = NSIG -> CombLFP P seed (lfp_candidate P seed).
Proof. intros seed Hl. apply CombLFP_intro with (n := lfp_fuel P); [reflexivity | apply stable; exact Hl]. Qed.

(** the driven state after a phase's external write *)
Theorem driven_lfp : forall pre ev, length pre = NSIG -> (changed_signal ev < NSIG)%nat ->
  CombLFP P (write_signal pre (changed_signal ev) (new_value ev)) (phase_driven_state P ev pre).
Proof.
  intros pre ev Hl Hs. unfold phase_driven_state. apply lfp_of_seed.
  rewrite length_write_signal; [exact Hl | rewrite Hl; exact Hs].
Qed.

Theorem phase_length : forall pre ev, length pre = NSIG -> (changed_signal ev < NSIG)%nat ->
  length (PhaseSemantics P ev pre) = NSIG.
Proof. intros pre ev Hl Hs. exact (phase_len P ev pre NSIG wb_ok Hl Hs). Qed.

(** the second settle of the phase (after the sequential update) *)
Theorem settle_lfp : forall pre ev, length pre = NSIG -> (changed_signal ev < NSIG)%nat ->
  CombLFP P (phase_seed P ev pre) (PhaseSemantics P ev pre).
Proof.
  intros pre ev Hl Hs. rewrite phase_eq. apply lfp_of_seed. exact (phase_seed_len P ev pre NSIG wb_ok Hl Hs).
Qed.
End @MOD@.
Print Assumptions @MOD@.stable.
Print Assumptions @MOD@.driven_lfp.
Print Assumptions @MOD@.phase_length.
Print Assumptions @MOD@.settle_lfp.
"""


def build(design, module, n):
    prof = json.loads((PROFILE / (design + '.json')).read_text())
    ast = prof['pipeline_roles']['ast']
    a = T.Ast(ast['file'], ast['signal_table'])
    t = TEXT
    for k, v in dict(DESIGN=design, AUTHOR=T.PROOF_AUTHOR, AST=ast['module'], MOD=module, PROG=ast['program'],
                     NSIG=str(len(a.sig)), N=str(n)).items():
        t = t.replace('@' + k + '@', v)
    exports = [f'{module}.{x}' for x in ('stable', 'driven_lfp', 'phase_length', 'settle_lfp')]
    return t, exports


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--design', default='steel')
    ap.add_argument('--module', required=True)
    ap.add_argument('--rounds', type=int, default=1)
    ap.add_argument('--out', required=True)
    ap.add_argument('--namespace')
    ap.add_argument('--accept', action='store_true')
    a = ap.parse_args()
    text, exports = build(a.design, a.module, a.rounds)
    if a.accept:
        import cpu_tmpl_accept as acc
        r = acc.accept(a.out, a.namespace, a.module, text, exports, [(T.json.loads((PROFILE / (a.design + '.json')).read_text())['pipeline_roles']['ast']['file'].rsplit('/', 1)[0], T.json.loads((PROFILE / (a.design + '.json')).read_text())['pipeline_roles']['ast']['module'].split('.')[0])],
                       extra=dict(generator='tools/cpu_tmpl_lfpnl.py', design=a.design, rounds=a.rounds))
        print(json.dumps(r, indent=1))
        sys.exit(0 if (r['accepted'] or r.get('coqc_accepted')) else 1)
    Path(a.out).write_text(text)
    print(a.out)
