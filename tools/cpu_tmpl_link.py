#!/usr/bin/env python3
"""Instruction-field links: the controller's field wires (opcode, funct3, funct7, rs1, rs2) are copy chains ending in a part
select of the ID instruction word register.  For each field emit, at any comb fixed point d,
  link_<f>: norm w (read d <field wire>) = norm w (Z.shiftr (norm 32 (read d <word reg>)) lsb)
(wire equations by checked_assignment_binding).  These connect the ISA decode inverse (CPUClassTableInverse.inv_<C>, stated on
the instruction word) to the FactsHold premises of the controller facts (cpu_tmpl_bzctl).
proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0. Untrusted generator."""
import json
import sys
from pathlib import Path
import cpu_tmpl_ast as T
import cpu_tmpl_roles as roles
import cpu_tmpl_edge as E

FIELDS = ('opcode', 'funct3', 'funct7', 'rs1', 'rs2')


def build(design, module):
    ast, pr, tr = roles.load_all(design)
    c = pr['controller']
    word = pr['fetch_slot']['word']['id']
    prog = pr['ast']['program']
    pmod = prog.split('.')[0]
    L = [f'Notation P := {prog.split(".")[-1]} (only parsing).']
    done = set()
    names = []

    def wire(s):
        if s in done:
            return
        done.add(s)
        cc = ast.comb[s]
        W = cc['width']
        L.extend([f'Definition orig_w{s}:Expr:={T.coq(cc["rhs"])}.',
                  f'Theorem eq_w{s} seed fixed:CombLFP P seed fixed->norm {W}(read_signal fixed {s}%nat)=norm {W}(eval_expr fixed orig_w{s}).',
                  f'Proof. intro HL. refine(checked_assignment_binding P _ {cc["k"]}%nat {cc["name"]} false orig_w{s} {W}%nat {s}%nat seed fixed eq_refl _ _ _ _ HL).',
                  ' all: first[vm_compute;reflexivity|(vm_compute;lia)]. Qed.'])
    for f in FIELDS:
        i = c[f]['id']
        chain = [i]
        while ast.comb[chain[-1]]['rhs'][0] == 'EVar' and ast.comb[chain[-1]]['rhs'][2] != word:
            chain.append(ast.comb[chain[-1]]['rhs'][2])
        # chain ends at the wire whose rhs is a part select of a copy of the word
        tail = ast.comb[chain[-1]]['rhs']
        assert tail[0] == 'ESel' and tail[3][0] == 'EConst', (f, tail)
        base = tail[2]
        w, lsb = tail[1], tail[3][2]
        # the base is the word register or a copy chain of it
        bchain = []
        b = base[2]
        while b != word:
            bchain.append(b)
            r = ast.comb[b]['rhs']
            assert r[0] == 'EVar', (f, r)
            b = r[2]
        for s in chain + bchain:
            wire(s)
        for s in bchain:
            if f'norm32_copy_{s}' not in '\n'.join(L):
                L.append(f'Theorem norm32_copy_{s} seed d : CombLFP P seed d -> norm 32(read_signal d {s}%nat)=norm 32(read_signal d {ast.comb[s]["rhs"][2]}%nat).')
                L.append(f'Proof. intro HL. rewrite(eq_w{s} seed d HL). unfold orig_w{s}. cbn[eval_expr]. rewrite norm_idempotent. reflexivity. Qed.')
        W = c[f]['width']
        prf = [f'Theorem link_{f} seed d : CombLFP P seed d -> norm {W}(read_signal d {i}%nat)=norm {W}(Z.shiftr(norm 32(read_signal d {word}%nat)){lsb}).',
               'Proof. intro HL.']
        for s in chain[:-1]:
            prf.append(f' rewrite(eq_w{s} seed d HL). unfold orig_w{s}. cbn[eval_expr]. rewrite norm_idempotent.')
        last = chain[-1]
        prf.append(f' rewrite(eq_w{last} seed d HL). unfold orig_w{last}. cbn[eval_expr].')
        for s in bchain:
            prf.append(f' rewrite(norm32_copy_{s} seed d HL).')
        prf.append(' rewrite ?norm_idempotent. reflexivity. Qed.')
        names.append(f'link_{f}')
        L.extend(prf)
    hdr = ('(** ' + design + ': instruction-field links of the ID controller, generated by tools/cpu_tmpl_link.py.\n'
           '    proof_author: ' + T.PROOF_AUTHOR + '; external_llm_api_calls=0. *)\n' +
           E.HDR.replace('@AST@', pr['ast']['module']).replace('@OPEN@', pmod))
    body = hdr + f'Module {module}.\n' + '\n'.join(L) + f'\nEnd {module}.\n' + ''.join(f'Print Assumptions {module}.{n}.\n' for n in names)
    return body, [f'{module}.{n}' for n in names], dict(fields=list(FIELDS))


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('--design', default='bzeeno')
    ap.add_argument('--module', default='BzTmplLink')
    ap.add_argument('--namespace')
    ap.add_argument('--out', required=True)
    ap.add_argument('--accept', action='store_true')
    a = ap.parse_args()
    body, exports, info = build(a.design, a.module)
    if not a.accept:
        Path(a.out).write_text(body); print(a.out, len(body.splitlines())); sys.exit(0)
    import cpu_tmpl_accept as acc
    prof = json.loads(Path(f'framework/auto-contract-profiles/{a.design}.json').read_text())
    lp = [(prof['pipeline_roles']['ast']['file'].rsplit('/', 1)[0], prof['pipeline_roles']['ast']['module'].split('.')[0])]
    r = acc.accept(a.out, a.namespace, a.module, body, exports, lp, extra=dict(generator='tools/cpu_tmpl_link.py', design=a.design, info=info))
    print(json.dumps(r, indent=1)); sys.exit(0 if r['accepted'] else 1)
