#!/usr/bin/env python3
"""Milestone 3 generator: assemble the D step (generic staged obligations -> infinite ITree).

Reads the role manifest + the accepted R/INV module (cpu_tmpl_inv) and emits a Coq module that
  * instantiates the generic StagedDesign / CycleObligations route (tools/cpu_pipeline_skeleton.py, mode plan)
    with the template relations (arch = retired RF/ROM/RAM/domain, front = coherent fields + PC cursor),
    the N=0 cycle plan (commit the slot PC iff the validity counter is 0), a rank, and the real reset as boot;
  * PROVES goal_boot (from inv_init) and goal_startup;
  * proves `refinement_given_cycle_facts`: the remaining goals (shape, transport, admission, observer, front,
    arch, rank) give the infinite RTL->ISA ITree refinement from the actual reset.
The remaining goals are the cycle-level facts of milestone 3 that are NOT yet proved on the template route.
"""
import json
import sys
from pathlib import Path
import cpu_tmpl_roles as roles
import cpu_tmpl_params as PR
import cpu_tmpl_ast as T
import cpu_pipeline_skeleton as sk


def manifest(design, module, inv_ns, cyc_ns='TmplDarkCycle.DarkTmplCycle.DarkTmplCycle'):
    ast, pr, tr = roles.load_all(design)
    tb = tr['target_binding']
    ds = tb['dstep']
    bank = pr['rf_write']['bank']['id']
    ctr = pr['fetch_slot']['validity']['counter']['id']
    ctrw = pr['fetch_slot']['validity']['counter']['width']
    pcr = pr['pc']['register']['id']
    arch = ' /\\ '.join(c.replace('{bank}', str(bank)) for c in ds['arch_clauses'])
    front = f'{inv_ns}.CoherentFields(rtl s) /\\ {cyc_ns}.env_ok s /\\ TmplDarkCursor.DarkTmplCursor.DarkTmplCursor.cursor_inv image s' + ''.join(' /\\ ' + c for c in ds['front_cursor'])
    P = ds['binders']
    prelude = [
        'Module ARCH := TmplDarkArch.DarkTmplArch.DarkTmplArch.',
        f'Definition tmpl_arch{P}(s:Runtime)(isa:FormalSpec.State):Prop:=ARCH.tmpl_arch image HC s isa.',
        f'Definition tmpl_front(image:list Z)(s:Runtime)(f:FormalSpec.State):Prop:={front}.',
        f'Definition tmpl_committing(s:Runtime):bool:=Z.eqb(norm {ctrw}(read_signal(rtl s){ctr}%nat))0.',
        f'Definition tmpl_plan_shape(s:Runtime):Shape(Token:=Z):=if tmpl_committing s then Advance(Some(norm 32(read_signal(rtl s){pcr}%nat)))else Advance None.',
        'Definition tmpl_plan_next(s:Runtime)(_ f:FormalSpec.State):FormalSpec.State:=if tmpl_committing s then snd(FormalSpec.run1 f)else f.',
        f'Definition tmpl_rank(s:Runtime)(_:FormalSpec.State):nat:={cyc_ns}.tmpl_rank s.',
    ]
    return dict(
        design=f'{design} (template route)', module=module, mode='plan',
        requires=['Lang.ExtendedSV', 'Ex.External.CPUProgramDomain'] + tb['imports'] + ds['extra_requires'] + ['TmplDarkArch.DarkTmplArch', 'TmplDarkCursor.DarkTmplCursor'] +
                 [inv_ns.split('.')[0] + '.' + inv_ns.split('.')[1], cyc_ns.split('.')[0] + '.' + cyc_ns.split('.')[1], pr['ast']['module'], 'coqutil.Word.Interface', 'riscv.Utility.Utility'],
        imports=['ExtendedSV', 'CPUProgramDomain'] + tb['open_modules'] + ds['extra_imports'],
        module_prelude=prelude,
        prelude=['Local Open Scope Z_scope.', 'Local Opaque PhaseSemantics phase_driven_state actual_cycle actual_observe.'],
        params=P, args=ds['args'], runtime='Runtime', token='Z',
        fields=dict(step='actual_cycle image', commits='actual_observe', effect='checked_pc_effect', pc='fun pc=>pc',
                    effect_sound='checked_pc_effect_sound', stages='fun _=>[]', arch='tmpl_arch image HC',
                    front='tmpl_front image', stage='fun _ _ _ _=>True'),
        plan_shape='tmpl_plan_shape', plan_next='tmpl_plan_next', rank='tmpl_rank', boot='actual_reset',
        initial='initial image', reset='actual_reset', proof_author=T.PROOF_AUTHOR), tb


def text(design, module, inv_ns, cyc_ns='TmplDarkCycle.DarkTmplCycle.DarkTmplCycle'):
    m, tb = manifest(design, module, inv_ns, cyc_ns)
    body = sk.skeleton(m).replace('Generated by tools/cpu_pipeline_skeleton.py; do not edit by hand.',
                                  'Generated by tools/cpu_tmpl_dstep.py via tools/cpu_pipeline_skeleton.py; do not edit by hand.')
    goals = []
    A = tb['dstep']['args']
    P = tb['dstep']['binders']
    extra = f'''
(** Template D step: every goal is PROVED here from the template R/INV, cursor and architecture layers; no open premise. *)
Theorem rfzero_initial image:TmplDarkRF.DarkTmplRF.DarkTmplRF.RFZero(read_signal(rtl actual_reset)@id:BANK@%nat)(initial image).
Proof. exact(ARCH.rfzero_initial image). Qed.
Lemma tmpl_arch_front_reset{P}:tmpl_arch {A} actual_reset(initial image)/\\tmpl_front image actual_reset(initial image).
Proof. destruct({inv_ns}.inv_init image)as[HA HCo]. unfold ArchRelated in HA. destruct HA as[Hc[Hn[HRF[HI HR]]]].
 split.
 - exact(ARCH.tmpl_arch_reset image HC).
 - unfold tmpl_front. split;[exact HCo|]. split;[exact {cyc_ns}.env_ok_reset|]. split;[exact(TmplDarkCursor.DarkTmplCursor.DarkTmplCursor.cursor_inv_reset image)|]. split;[exact Hc|]. exact Hn. Qed.
Lemma boot_proved{P}:goal_boot {A}.
Proof. unfold goal_boot. destruct(tmpl_arch_front_reset {A})as[Ha Hf].
 exact(staged_initial(design {A})actual_reset(initial image)0%nat eq_refl Ha Hf). Qed.
Lemma startup_proved{P}:goal_startup {A}.
Proof. unfold goal_startup. reflexivity. Qed.
Lemma shape_proved{P}:goal_shape {A}.
Proof. unfold goal_shape. intros s r f _. cbn[design sd_stages]. unfold plan_shape,tmpl_plan_shape. destruct(tmpl_committing s);reflexivity. Qed.
Lemma transport_proved{P}:goal_transport {A}.
Proof. unfold goal_transport. intros s r f _. cbn[design sd_stages]. apply transport_no_stages.
 unfold plan_shape,tmpl_plan_shape. destruct(tmpl_committing s);discriminate. Qed.
Lemma physical_env{P} s r f:staged_physical (design {A}) s r f->{cyc_ns}.env_ok s.
Proof. intros[_[Hf _]]. cbn[design sd_front]in Hf. unfold tmpl_front in Hf. destruct Hf as[_[He _]]. exact He. Qed.
Lemma observer_proved{P}:goal_observer {A}.
Proof. unfold goal_observer. intros s r f HP. pose proof(physical_env {A} s r f HP)as HE.
 cbn[design sd_commits sd_stages]. unfold plan_shape,tmpl_plan_shape,tmpl_committing.
 rewrite({cyc_ns}.observe_eq s HE). destruct(Z.eqb(norm 2(read_signal(rtl s)@id:VALID_CTR@%nat))0);reflexivity. Qed.
Lemma rank_proved{P}:goal_rank {A}.
Proof. unfold goal_rank,OrderedWaitDecreases. intros s isa HJ Hsil.
 destruct HJ as[f[HP _]]. pose proof(physical_env {A} s isa f HP)as HE.
 rewrite({cyc_ns}.observe_eq s HE)in Hsil.
 destruct(Z.eqb(norm 2(read_signal(rtl s)@id:VALID_CTR@%nat))0)eqn:EF;[discriminate|].
 apply Z.eqb_neq in EF. unfold tmpl_rank. exact({cyc_ns}.rank_dec image s HE EF). Qed.
Definition goal_cursor{P}:Prop:=forall s retired frontier,staged_physical (design {A}) s retired frontier->
 architectural_cursor(rtl(actual_cycle image s))=word.unsigned(getPc((plan_next {A}) s retired frontier)) /\\ word.unsigned(getNextPc((plan_next {A}) s retired frontier))=norm 32(architectural_cursor(rtl(actual_cycle image s))+4).
Lemma cursor_proved{P}:goal_cursor {A}.
Proof. intros s r f HP. pose proof HP as [Harch[Hfront Hst]].
 cbn[design sd_stages]in Hst. apply sr_nil_inv in Hst. subst f.
 cbn[design sd_arch]in Harch. unfold tmpl_arch,ARCH.tmpl_arch in Harch. destruct Harch as[HRF[_[_[Hh _]]]]. cbn[holds ARCH.jf_domain]in Hh.
 cbn[design sd_front]in Hfront. unfold tmpl_front in Hfront. destruct Hfront as[HCoh[_[Ci[Hc Hn]]]].
 unfold plan_next,tmpl_plan_next,tmpl_committing.
 exact(TmplDarkCursor.DarkTmplCursor.DarkTmplCursor.cursor_next image HC s r Ci HCoh HRF Hh Hc Hn). Qed.
Lemma front_proved{P}:goal_front {A}.
Proof. unfold goal_front. intros s r f HP. pose proof(physical_env {A} s r f HP)as HE.
 destruct(cursor_proved {A} s r f HP)as[C1 C2]. destruct HP as[_[Hfront _]]. cbn[design sd_front]in Hfront. unfold tmpl_front in Hfront. destruct Hfront as[_[_[Ci _]]].
 cbn[design sd_front sd_step]. unfold tmpl_front.
 split;[exact({cyc_ns}.coherent_step image s HE)|]. split;[exact({cyc_ns}.env_step image s HE)|].
 split;[exact(TmplDarkCursor.DarkTmplCursor.DarkTmplCursor.cursor_inv_step image s Ci)|]. split;assumption. Qed.
Lemma pc_effect_of_run1 a b:FormalSpec.run1 a=(Some tt,b)->checked_pc_effect(word.unsigned(getPc a))a=Some b.
Proof. intro HR. unfold checked_pc_effect. rewrite Z.eqb_refl,HR. reflexivity. Qed.
Lemma admission_proved{P}:goal_admission {A}.
Proof. unfold goal_admission. intros s r f HP. pose proof HP as [Harch[Hfront Hst]].
 cbn[design sd_stages]in Hst. apply sr_nil_inv in Hst. subst f.
 unfold shape_admission,plan_shape,plan_next,tmpl_plan_shape,tmpl_plan_next. destruct(tmpl_committing s)eqn:HK;cbn[shape_admitted].
 - cbn[design sd_arch]in Harch. unfold tmpl_arch,ARCH.tmpl_arch in Harch. destruct Harch as[_[_[_[Hh _]]]]. cbn[holds ARCH.jf_domain]in Hh. destruct Hh as[index HAt].
   destruct(CPUJumpFamilyProgramDomain.CPUJumpFamilyProgramDomain.checked_run1_total image index r HC HAt)as[post HRun].
   cbn[design sd_front]in Hfront. unfold tmpl_front in Hfront. destruct Hfront as[_[_[_[Hc _]]]].
   unfold tmpl_committing in HK. apply Z.eqb_eq in HK. unfold architectural_cursor in Hc. rewrite HK in Hc. cbn in Hc.
   rewrite HRun. cbn[snd]. split;[|exact I]. cbn[design sd_effect]. rewrite Hc. exact(pc_effect_of_run1 _ _ HRun).
 - reflexivity.
Qed.
Lemma arch_proved{P}:goal_arch {A}.
Proof. unfold goal_arch. intros s r f HP advanced Hch. pose proof HP as [Harch[Hfront Hst]].
 cbn[design sd_stages]in Hst. apply sr_nil_inv in Hst. subst f. pose proof(physical_env {A} s r r HP)as HE.
 cbn[design sd_arch sd_step]. unfold tmpl_arch in Harch|-*.
 cbn[design sd_front]in Hfront. unfold tmpl_front in Hfront. destruct Hfront as[HCoh[_[Ci[Hc Hn]]]].
 unfold plan_shape,tmpl_plan_shape in Hch. destruct(tmpl_committing s)eqn:HK.
 - unfold tmpl_committing in HK. apply Z.eqb_eq in HK.
   cbn[design sd_stages sd_effect shape_retiring opt hd app]in Hch.
   inversion Hch as[|a t b ts c Hef Hch2]. subst. inversion Hch2. subst.
   destruct(checked_pc_effect_sound _ _ _ Hef)as[Hrun Hpc].
   destruct Ci as[HE2[Hs Hp]]. destruct Hp as[Hp0 _].
   destruct(Hp0 HK)as[Hlink _]. rewrite Hpc in Hlink.
   exact(ARCH.arch_commit image HC s r _ HE Harch HCoh HK(Hs(or_introl HK))Hpc Hlink Hrun).
 - unfold tmpl_committing in HK. apply Z.eqb_neq in HK.
   cbn[design sd_stages sd_effect shape_retiring opt hd app]in Hch.
   inversion Hch. subst.
   exact(ARCH.arch_bubble image HC s _ HE Harch HK). Qed.
Theorem refinement{P}:
 ordered_scheduler(actual_cycle image)actual_observe actual_reset ≈
 FormalSpec.riscv_itree_with_state(initial image).
Proof.
 exact(assembled {A}(shape_proved {A})(transport_proved {A})(admission_proved {A})(observer_proved {A})(front_proved {A})(arch_proved {A})(rank_proved {A})(boot_proved {A})(startup_proved {A})). Qed.
'''
    end = f'End {module}.\n'
    k = body.rindex(end)
    body = body[:k] + extra + end + f'Print Assumptions {module}.boot_proved.\nPrint Assumptions {module}.startup_proved.\nPrint Assumptions {module}.refinement.\n' + \
        body[k + len(end):]
    exports = [f'{module}.assembled', f'{module}.boot_proved', f'{module}.startup_proved', f'{module}.refinement']
    return PR.Params(design).render(body), exports, goals


if __name__ == '__main__':
    import argparse
    import cpu_tmpl_accept as acc
    ap = argparse.ArgumentParser()
    ap.add_argument('--design', default='darkriscv')
    ap.add_argument('--module', default='DarkTmplStep')
    ap.add_argument('--namespace')
    ap.add_argument('--inv', default='TmplDarkInv.DarkTmplInv.DarkTmplInv')
    ap.add_argument('--out', required=True)
    ap.add_argument('--provider', action='append', default=[])
    ap.add_argument('--accept', action='store_true')
    a = ap.parse_args()
    body, exports, goals = text(a.design, a.module, a.inv)
    if not a.accept:
        Path(a.out).write_text(body)
        print(a.out, len(body.splitlines()))
        sys.exit(0)
    ast, pr, tr = roles.load_all(a.design)
    prov = [dict(namespace=x.split('=')[0], directory=str(Path(x.split('=')[1]).resolve())) for x in a.provider]
    lp = [(d['directory'], d['namespace']) for d in json.loads(Path(f'framework/auto-contract-profiles/{a.design}.json').read_text())['coq_load_paths']
          if d['namespace'] == 'Dark38'] + [tuple(x) for x in tr['target_binding']['extra_loadpaths']]
    r = acc.accept(a.out, a.namespace, a.module, body, exports, lp, providers=prov,
                   extra=dict(generator='tools/cpu_tmpl_dstep.py', design=a.design, open_goals=goals,
                              scope='boot and startup proved; the listed goals are open premises'))
    print(json.dumps(r, indent=1))
    sys.exit(0 if r['accepted'] else 1)
