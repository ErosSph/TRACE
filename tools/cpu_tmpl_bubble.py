#!/usr/bin/env python3
"""Bubble (non-committing) cycle controller facts: FLUSH in {1,2,3}, XRES in {0,1}, HLT = 0.

For each case the register-file write value and the data-request wire are derived by the same condition-directed
reduction as the per-class controls (tools/cpu_tmpl_controls.py).  No slot flag is fixed: the FLUSH mask makes them
irrelevant, and the reduction must discover that by itself (an unmasked flag would make the generation fail).
"""
import argparse
import json
import sys
from pathlib import Path
import cpu_tmpl_controls as ctl

CASES = [(x, k) for x in (0, 1) for k in (1, 2, 3)]


class BubbleGen(ctl.Gen):
    def premises(self, c):
        i = self.id
        return [(1, i['xres'], c['xres']), (1, i['halt'], 0), (2, i['flush'], c['flush'])]

    def expected(self, c):
        i = self.id
        rd = f'(norm 5(read_signal fixed {i["rd"]}%nat))'
        if c['xres']:
            val = '0'
        else:
            val = f'if Z.eqb 0 {rd} then 0 else norm 32(read_signal fixed {i["dreg"]}%nat)'
        return [('rf', 'stmt', 'rf_value', val), ('ddreq', 'wire', i['ddreq'], '0')]


def classes():
    return [dict(name=f'Bub{x}_{k}', xres=x, flush=k) for x, k in CASES]


def build(design, module):
    g = BubbleGen(design, module)
    body = [g.gen_class(c)[0] for c in classes()]
    pre = ctl.PREAMBLE.replace('@AST@', g.ast_module).replace('@ASTNS@', g.ast_module.split('.')[-1]).replace('@PROG@', g.prog)
    hdr = f'(** {design}: bubble-cycle controller facts, generated by tools/cpu_tmpl_bubble.py. proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0. *)\n'
    exports = [f'{module}.{c["name"]}_controls' for c in classes()]
    text = hdr + pre + f'Module {module}.\n' + '\n'.join(g.head) + '\n' + '\n'.join(body) + f'End {module}.\n'
    text += ''.join(f'Print Assumptions {e}.\n' for e in exports)
    return text, exports


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--design', default='darkriscv')
    ap.add_argument('--module', default='DarkTmplBubble')
    ap.add_argument('--namespace')
    ap.add_argument('--out', required=True)
    ap.add_argument('--accept', action='store_true')
    a = ap.parse_args()
    text, exports = build(a.design, a.module)
    if not a.accept:
        Path(a.out).write_text(text)
        print(a.out)
        sys.exit(0)
    import cpu_tmpl_accept as acc
    lp = [(d['directory'], d['namespace']) for d in json.loads(Path(f'framework/auto-contract-profiles/{a.design}.json').read_text())['coq_load_paths']
          if d['namespace'] == 'Dark38']
    r = acc.accept(a.out, a.namespace, a.module, text, exports, lp, extra=dict(generator='tools/cpu_tmpl_bubble.py', design=a.design))
    print(json.dumps(r, indent=1))
    sys.exit(0 if r['accepted'] else 1)
