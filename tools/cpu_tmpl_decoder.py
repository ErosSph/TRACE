#!/usr/bin/env python3
"""Per-class decoder facts for a multi-output blocking decoder process (template route, N-stage designs).

Role discovery (no design names): the combinational process whose body has a case on word[6:0] with many
arms is the decoder, the word is the case scrutinee's base variable.  For every ISA class (cpu_isa_classes +
cpu_class_table.isa_f3 / hyps) the facts are the opcode/funct3/funct7 slices the ISA decode fixes; the Python
mirror of ExtendedSVSymExec (cpu_tmpl_symexec) finds the extra slices it can derive and the BASE facts (decoder
inputs such as illegal_c_insn_i = 0) the class needs.  Coq re-checks everything (ExtendedSVSymExec.comb_process_outs).
Theorem per class:  CombLFP P seed fixed -> FactsHold fixed facts_C -> DecOut fixed outs_C.
proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0.
"""
import argparse
import json
import sys
from pathlib import Path
import cpu_tmpl_ast as T
import cpu_tmpl_symexec as X
import cpu_isa_classes as isa
import cpu_class_table as ct

PROFILE = Path('framework/auto-contract-profiles')
PREAMBLE = """From Coq Require Import ZArith List Bool.
Require Import Lang.ExtendedSV Lang.ExtendedSVSymExec @AST@.
Import ListNotations ExtendedSV ExtendedSVSymExec @ASTNS@.
Local Open Scope Z_scope.
Definition P:=@PROG@.
"""


def find_decoder(ast):
    for k, i in enumerate(ast.comb_ids):
        found = []

        def walk(s):
            if s[0] == 'SSeq':
                for c in s[1]:
                    walk(c)
            elif s[0] == 'SIf':
                walk(s[2]); walk(s[3])
            elif s[0] == 'SCase':
                e = s[1]
                if (e[0] == 'ESel' and e[1] == 7 and e[2][0] == 'EVar' and e[2][1] == 32 and e[3] == ('EConst', 5, 0)
                        and len(s[2]) >= 10):
                    found.append(e[2])
        walk(ast.procs[i]['body'])
        if found:
            return dict(process=i, comb_index=k, word=found[0], name=ast.names[i])
    raise ValueError('no decoder process')


def class_slices(word, c):
    sl = lambda w, l: ('ESel', w, word, ('EConst', 5, l))
    out = [(sl(7, 0), c['opcode'])]
    if ct.isa_f3(c) is not None:
        out.append((sl(3, 12), ct.isa_f3(c)))
    if c['name'] in ct.SHIFT_IMM or c['group'] == 'OP':
        out.append((sl(7, 25), c['funct7']))
    return out


def coq_facts(fl):
    return '[' + '; '.join(f'({T.coq(e)},{z})' for e, z in fl) + ']'


class Gen:
    def __init__(self, ast_file, table, fuel):
        self.ast = T.Ast(ast_file, table)
        self.dec = find_decoder(self.ast)
        self.fuel = fuel

    def run_class(self, c):
        X_ = X._Tracing
        old = X.Exec
        X.Exec = X_
        try:
            facts, base, ov = X.close_facts(self.ast.procs[self.dec['process']]['body'], self.dec['word'], [], self.fuel,
                                            class_slices(self.dec['word'], c))
        finally:
            X.Exec = old
        base_facts = [(e, 0) for e in base]
        return facts + base_facts, ov

    def theorem(self, c):
        facts, ov = self.run_class(c)
        outs = sorted((r, w, z) for r, (w, z) in ov.items())
        n = c['name']
        t = [f'Definition facts_{n}:Facts:={coq_facts(facts)}.',
             f'Definition outs_{n}:list((signal*nat)*Z):=[' + '; '.join(f'(({r}%nat,{w}%nat),{z})' for r, w, z in outs) + '].',
             f'Theorem {n}_decoder seed fixed:CombLFP P seed fixed->FactsHold fixed facts_{n}->DecOut fixed outs_{n}.',
             f'Proof. intros HL HF. refine(comb_process_outs P _ {self.dec["comb_index"]}%nat {self.dec["name"]} facts_{n} outs_{n} seed fixed eq_refl _ _ HF HL _).',
             ' - vm_compute;reflexivity.',
             ' - vm_compute;reflexivity.',
             ' - vm_compute;reflexivity.',
             'Qed.']
        return '\n'.join(t) + '\n', len(outs), facts


def build(ast_file, table, ast_module, prog, module, names, fuel):
    g = Gen(ast_file, table, fuel)
    cls = [c for c in isa.classes() if names == 'all' or c['name'] in names.split(',')]
    body, info = [], {}
    for c in cls:
        txt, n, facts = g.theorem(c)
        body.append(txt)
        info[c['name']] = dict(outputs=n, facts=len(facts))
    pre = PREAMBLE.replace('@AST@', ast_module).replace('@ASTNS@', ast_module.split('.')[-1]).replace('@PROG@', prog)
    hdr = (f'(** per-class decoder facts, generated by tools/cpu_tmpl_decoder.py (decoder process {g.dec["name"]},\n'
           f'    word signal {g.dec["word"][2]}).  proof_author: {T.PROOF_AUTHOR}; external_llm_api_calls=0. Generated. *)\n')
    exports = [f'{module}.{c["name"]}_decoder' for c in cls]
    text = hdr + pre + f'Module {module}.\n' + '\n'.join(body) + f'End {module}.\n' + ''.join(f'Print Assumptions {e}.\n' for e in exports)
    return text, exports, info, g


def run_accept(ast_file, table, ast_module, prog, module, namespace, names, out, fuel, design):
    import cpu_tmpl_accept as acc
    text, exports, info, g = build(ast_file, table, ast_module, prog, module, names, fuel)
    return acc.accept(out, namespace, module, text, exports, [], extra=dict(
        generator='tools/cpu_tmpl_decoder.py', design=design, classes=len(info), per_class=info,
        decoder_process=g.dec['name'], ast_sha256=acc.sha(ast_file)))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--design', default='cv32e40p')
    ap.add_argument('--classes', default='all')
    ap.add_argument('--module', default='CvTmplDecoder')
    ap.add_argument('--out', required=True)
    ap.add_argument('--namespace')
    ap.add_argument('--accept', action='store_true')
    a = ap.parse_args()
    prof = json.loads((PROFILE / (a.design + '-tmpl.json')).read_text())['pipeline_roles']['ast']
    args = (prof['file'], prof['signal_table'], prof['module'], prof['program'].split('.')[-1])
    if a.accept:
        r = run_accept(*args, a.module, a.namespace, a.classes, a.out, 512, a.design)
        print(json.dumps({k: r[k] for k in r if k != 'per_class'}, indent=1))
        sys.exit(0 if r['accepted'] else 1)
    text, exports, info, g = build(*args, a.module, a.classes, 512)
    Path(a.out).write_text(text)
    print(a.out, len(text.splitlines()), 'lines;', len(exports), 'exports')
