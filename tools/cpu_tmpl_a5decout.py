def class_text(c):
    g, opc, alu = AO.CL[c]
    n = AO.NF.get(c, 3)
    fs = ' '.join(f'a{k}' for k in range(n))
    ctor = f'(Decode.{c} {fs})'
    k = KIND[c]
    L = [f'Lemma dec_{c} seed d w {fs} : CombLFP P seed d -> R d 32 136 = w -> Decode.decode Decode.RV32I w = Decode.IInstruction {ctor} -> DecRes d {ctor} w.',
         f'Proof. intros HL h136 Hdec. pose proof (w157 seed d w HL h136) as h157. destruct (CI.inv_{c} w {fs} Hdec) as [_ Hb].',
         f' assert (HFa : FactsHold d D.facts_{c}).',
         ' { intros e z Hin. cbn [D.facts_' + c + '] in Hin. repeat (destruct Hin as [E|Hin]; [injection E as <- <-|]); try (destruct Hin);',
         '   cbn [eval_expr]; rewrite h157; rewrite selw by lia; match goal with |- bitSlice w ?a ?b = _ => let bb := eval vm_compute in b in change b with bb end;']
    if k == 'R':
        L.append('   destruct Hb as (B1 & B2 & B3); first [exact B1 | exact B2 | rewrite (bit_of_slice w 25 32 _ 30 31 ltac:(lia) ltac:(lia) eq_refl B3); reflexivity | rewrite (bit_of_slice w 25 32 _ 25 26 ltac:(lia) ltac:(lia) eq_refl B3); reflexivity]. }')
    elif k == 'S':
        L.append('   destruct Hb as (B1 & B2 & B3 & B4); first [exact B1 | exact B2 | rewrite (bit_of_slice w 26 32 _ 30 31 ltac:(lia) ltac:(lia) eq_refl B3); reflexivity | exact B4]. }')
    elif n == 2 or c == 'Lui':
        L.append('   exact Hb. }')
    else:
        L.append('   destruct Hb as (B1 & B2); first [exact B1 | exact B2]. }')
    L += [f' pose proof (decout_fhold d _ (D.{c}_dec seed d HL HFa)) as HF.',
          ' unfold DecRes. split; [|split; [|split]].',
          ' 1-3: rewrite <- (pe_sound [] d _ HF (bhold_nil d)), <- mfold_sound; vmmf; reflexivity.']
    if k == 'R':
        L.append(' intros v Hv. discriminate Hv.')
    else:
        L.append(f' intros v Hv. unfold IV.immv in Hv. pose proof (f_equal (fun o => match o with Some x => x | None => 0 end) Hv) as Ev. cbv beta iota in Ev. subst v.')
        L.append(f' rewrite (D.{c}_imm_isa seed d HL HFa), h157. reflexivity.')
    L.append('Qed.')
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--classes', default='')
    a = ap.parse_args()
    classes = a.classes.split(',') if a.classes else list(AO.CL)
    L = [HEAD.replace('@AUTHOR@', AUTHOR)]
    for c in classes:
        L.append(class_text(c))
    disp = ' | '.join(f'exact (dec_{c} seed d w _ _{"" if AO.NF.get(c, 3) == 2 else " _"} HL H136 Hdec)' for c in classes)
    L += ['Theorem dec_out seed d w i : CombLFP P seed d -> R d 32 136 = w -> Decode.decode Decode.RV32I w = Decode.IInstruction i -> JF.legal_instruction i = true -> DecRes d i w.',
          'Proof. intros HL H136 Hdec HLg. destruct i.', ' all: try (exfalso; cbv in HLg; discriminate HLg).', f' all: first [{disp}].', 'Qed.',
          'End A5TmplDecOut.', 'Print Assumptions A5TmplDecOut.dec_out.']
    Path(a.out).write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
