#!/usr/bin/env python3
"""NERV wire equations: for each requested root R written by exactly ONE combinational process whose body is a single assignment,
`wire_R: CombLFP P seed d -> norm w (read d R) = norm w (eval_expr d RHS)` through hxrun_comb_lfp (no facts).  Untrusted generator, Coq checks.
proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0."""
import argparse, json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import cpu_tmpl_nvlib as L
import cpu_tmpl_ast as T

ROOTS = [16, 17, 7, 19, 20, 43, 52, 50, 47, 51, 49, 48, 53, 54, 55, 59]


def show(e):
    if e[0] == 'EConst': return f'(EConst {e[1]} {e[2]})'
    if e[0] == 'EVar': return f'(EVar {e[1]} {e[2]}%nat)'
    if e[0] in ('ESel', 'EConcat'): return f'({e[0]} {e[1]} {show(e[2])} {show(e[3])})'
    if e[0] == 'EReplicate': return f'(EReplicate {e[1]} {e[2]} {show(e[3])})'
    if e[0] == 'EExtend': return f'(EExtend {e[1]} {"true" if e[2] else "false"} {show(e[3])})'
    if e[0] == 'EUnary': return f'(EUnary {e[1]} {e[2]} {show(e[3])})'
    if e[0] == 'EBinary': return f'(EBinary {e[1]} {e[2]} {show(e[3])} {show(e[4])})'
    if e[0] == 'ECond': return f'(ECond {e[1]} {show(e[2])} {show(e[3])} {show(e[4])})'
    raise ValueError(e)


def build(roots=ROOTS, module='NervTmplWire'):
    a = T.Ast('experiments/framework/generated/nerv-lit/NervLitAST.v', 'experiments/framework/generated/nerv-lit/report.json')
    out = ['(** NERV wire equations (single-assignment combinational wires). Generated by tools/cpu_tmpl_nvwire.py.',
           '    proof_author: LLM-generated: Claude Code (claude-sonnet-5-5); external_llm_api_calls=0. Generated. *)',
           'From Coq Require Import ZArith List Bool.',
           'Require Import Lang.ExtendedSV Lang.ExtendedSVSymExec Lang.ExtendedSVFactChain Lang.ExtendedSVSymExecSym Lang.ExtendedSVEval4',
           ' Lang.ExtendedSVSymExecOverlay4 Lang.ExtendedSVSymExecHavoc NervLit.NervLitAST.',
           'Import ListNotations ExtendedSV ExtendedSVSymExec ExtendedSVFactChain ExtendedSVSymExecSym ExtendedSVEval4 ExtendedSVSymExecOverlay4 ExtendedSVSymExecHavoc.',
           'Local Open Scope Z_scope.', f'Module {module}.', 'Notation P := NervLitAST.nerv_program.',
           'Definition ps := filter is_comb (processes P).', L.wtab_text().strip(),
           'Lemma wtab_ok : tab_okb ps wtab = true. Proof. vm_compute; reflexivity. Qed.',
           'Definition ps_eq : filter is_comb (processes P) = ps := eq_refl.',
           'Lemma nofacts s : FactsHold s []. Proof. intros e z H. destruct H. Qed.']
    names = []
    for r in roots:
        c = a.comb.get(r)
        assert c is not None, r
        w = a.sig[r]['width']
        k = L.COMB_POS[[p for p in L.COMB if r in p['writers']][0]['index']]
        assert len([p for p in L.COMB if r in p['writers']]) == 1, r
        rhs = show(c['rhs'])
        out += [f'Definition proc_{r} : Process := match nth_error ps {k} with Some q => q | None => {{| process_kind:=Initial; process_events:=[]; process_body:=SSkip; process_source_line:=0%nat |}} end.',
                f'Lemma nth_{r} : nth_error ps {k} = Some proc_{r}. Proof. vm_compute; reflexivity. Qed.',
                f'Lemma hx_{r} : hxexec [] (statement_fuel P) (nbfix (process_body proc_{r})) [] = Some [({r}%nat,({w}%nat,{rhs}))]. Proof. vm_compute; reflexivity. Qed.',
                f'Lemma inp_{r} : facts_inputs_okb [] wtab {k} = true. Proof. vm_compute; reflexivity. Qed.',
                f'Lemma lt_{r} : wr_lt wtab {r}%nat (S {k}) = true. Proof. vm_compute; reflexivity. Qed.',
                f'Lemma ie_{r} : inputs_okb wtab {k} {rhs} = true. Proof. vm_compute; reflexivity. Qed.',
                f'Theorem wire_{r} seed d : CombLFP P seed d -> norm {w} (read_signal d {r}%nat) = norm {w} (eval_expr d {rhs}).',
                f'Proof. intro HL. exact (hxrun_comb_lfp P ps wtab {k} proc_{r} [] _ seed d ps_eq (tab_okb_sound _ _ wtab_ok) nth_{r} inp_{r} (nofacts d) HL hx_{r} {r}%nat {w}%nat {rhs} eq_refl lt_{r} ie_{r}). Qed.']
        names.append(f'wire_{r}')
    out += [f'End {module}.', 'Goal True. idtac "TMPL_AUDIT_BEGIN". exact I. Qed.'] + [f'Print Assumptions {module}.{n}.' for n in names]
    return '\n'.join(out) + '\n', [f'{module}.{n}' for n in names]


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['gen', 'accept'])
    ap.add_argument('--out')
    a = ap.parse_args()
    text, exports = build()
    if a.cmd == 'gen':
        Path(a.out).write_text(text); print(len(text.splitlines()), 'lines'); sys.exit(0)
    import cpu_tmpl_accept as acc
    lp = [('experiments/framework/generated/nerv-lit', 'NervLit')]
    r = acc.accept(a.out, 'TmplNervWire', 'NervTmplWire', text, exports, lp, providers=[], factcheck=False, extra=dict(generator='tools/cpu_tmpl_nvwire.py', design='nerv'))
    print(json.dumps({k: v for k, v in r.items() if k != 'info'}, indent=1)); sys.exit(0 if r.get('coqc_accepted') else 1)
